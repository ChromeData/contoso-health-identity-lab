# --- run records (test/e2e.sh --evidence-dir, dr-drill.sh --evidence-dir) -----
# A run record is a folder of non-secret files plus SHA256SUMS. These two
# helpers are the guard and the check; e2e-dynamic-db.sh has its own copy.
# run_record_unsafe DIR -> 0 when the record holds something it must not:
#   a 32+ character alphanumeric run (a generated password, key or token)
#   that is not a lowercase 64-hex SHA-256, an absolute local path, or a
#   Vault token prefix. SHA256SUMS itself is skipped (64-hex by design).
run_record_unsafe() {
  local hits
  hits=$(grep -rhoE --exclude=SHA256SUMS '[A-Za-z0-9]{32,}' "$1" 2>/dev/null | grep -vxE '[0-9a-f]{64}' || true)
  [[ -n "$hits" ]] && return 0
  grep -rEq --exclude=SHA256SUMS '(/Users/|/home/|/private/tmp|/var/folders|hvs\.[A-Za-z0-9])' "$1" && return 0
  return 1
}
# run_record_seal STAGE DEST FILE... : refuse an unsafe stage, else write
# SHA256SUMS over FILE... and copy them (+ SHA256SUMS) to DEST (0644).
run_record_seal() {
  local stage="$1" dest="$2"; shift 2
  if run_record_unsafe "$stage"; then
    printf 'RECORD REFUSED: a secret-shaped string or local path is in the run record; nothing written to %s\n' "$dest"
    return 1
  fi
  (cd "$stage" && shasum -a 256 "$@" > SHA256SUMS)
  (umask 022; mkdir -p "$dest")
  local f; for f in "$@" SHA256SUMS; do cp "$stage/$f" "$dest/$f"; done
  chmod 644 "$dest"/*
}
# run_record_verify DIR JSON JQ_PASS_FILTER : SHA256SUMS verifies, the JSON
# passes the filter (an all-PASS run), nothing unsafe, and its code
# fingerprint (run_record_code_check) is present and self-consistent.
# Prints PASS/FAIL lines (and NOTE lines, which are information, not checks).
run_record_verify() {
  local d="$1" j="$2" filter="$3" bad=0
  [[ -s "$d/SHA256SUMS" && -s "$d/$j" ]] || { echo "FAIL  record incomplete: $d"; return 1; }
  if (cd "$d" && shasum -a 256 -c SHA256SUMS >/dev/null 2>&1); then echo "PASS  SHA256SUMS verifies"; else echo "FAIL  SHA256SUMS"; bad=1; fi
  if jq -e "$filter" "$d/$j" >/dev/null 2>&1; then echo "PASS  $j: an all-PASS run"; else echo "FAIL  $j is not an all-PASS run"; bad=1; fi
  if run_record_unsafe "$d"; then echo "FAIL  secret-shaped string or local path in the record"; bad=1; else echo "PASS  no password-shaped string, token or local path"; fi
  run_record_code_check "$d" "$j" || bad=1
  return $bad
}

# --- code fingerprint: WHICH scripts a run record proves --------------------------
# A record names the code it ran: code.sha256sums in the record, in shasum
# format ("<sha256>  <path>", byte-sorted by path, paths relative to lab/pam),
# covering every file git tracks under lab/pam except *.md (scripts, lib.sh,
# compose files, policy, fixtures, the seed script), taken when the run
# STARTS. The record's JSON carries {sha256 of that list, file count, list
# name}; SHA256SUMS seals both. (A list file, not a JSON path->hash map: secret
# scanners read '"...access-....xml": "<hex>"' as an API key.)
code_files() { # every non-doc file git would track under lab/pam, byte-sorted
  git ls-files --cached --others --exclude-standard -- . | { grep -v '\.md$' || true; } | LC_ALL=C sort -u \
    | while IFS= read -r f; do if [[ -f "$f" ]]; then printf '%s\n' "$f"; fi; done
}
code_sums() { # -> "<sha256>  <path>" lines for code_files; fails outside a git checkout
  local list
  list=$(code_files) || { echo "code_sums: git ls-files failed (not a git checkout?)" >&2; return 1; }
  [[ -n "$list" ]] || { echo "code_sums: no files under lab/pam" >&2; return 1; }
  printf '%s\n' "$list" | tr '\n' '\0' | xargs -0 shasum -a 256
}
code_meta() { # code_meta SUMS_FILE -> the JSON a record carries about it
  jq -n --arg sha "$(shasum -a 256 < "$1" | cut -d' ' -f1)" --argjson n "$(grep -c . "$1")" \
    '{scope: "lab/pam: every file git tracks there except *.md, hashed when the run started",
      list: "code.sha256sums", sha256: $sha, files: $n}'
}
# run_record_code_check DIR JSON : PASS/FAIL - .code is present (a record whose
# schema predates it gets a NOTE instead), the list it names is in the record,
# hashes to .code.sha256, has .code.files well-formed lines. NOTE - whether
# those files still match the tree here: a record stays valid after the code
# moves on; it proves the code it names.
run_record_code_check() {
  local d="$1" j="$2" list want n changed added
  if ! jq -e '.code | type == "object"' "$d/$j" >/dev/null 2>&1; then
    if jq -e '(.schema // "") | . == "" or test("/v1$")' "$d/$j" >/dev/null 2>&1; then
      echo "NOTE  $j has no code fingerprint (written before records carried one): the script version it proves is not recorded"
      return 0
    fi
    echo "FAIL  $j: code fingerprint missing"; return 1
  fi
  list="$d/$(jq -r '.code.list // "code.sha256sums"' "$d/$j" | tr -d '/')"
  want=$(jq -r '.code.sha256 // ""' "$d/$j"); n=$(jq -r '.code.files // 0' "$d/$j")
  if [[ -s "$list" && "$want" =~ ^[0-9a-f]{64}$ && "$(shasum -a 256 < "$list" | cut -d' ' -f1)" == "$want" \
        && "$(grep -c . "$list")" == "$n" && "$n" -gt 0 ]] \
     && ! grep -vqE '^[0-9a-f]{64}  [A-Za-z0-9._][A-Za-z0-9._/+-]*$' "$list" && ! grep -qF '../' "$list"; then
    echo "PASS  $j: code fingerprint present and consistent ($n files in $(basename "$list"), sha256 ${want:0:16}...)"
  else
    echo "FAIL  $j: code fingerprint malformed, or $(basename "$list") missing / altered"; return 1
  fi
  changed=$(while read -r h p; do
      if [[ ! -f "$p" ]]; then printf '%s (gone) ' "$p"
      elif [[ "$(shasum -a 256 "$p" | cut -d' ' -f1)" != "$h" ]]; then printf '%s ' "$p"; fi
    done < "$list")
  added=$(LC_ALL=C comm -13 <(awk '{ print $2 }' "$list" | LC_ALL=C sort) <(code_files 2>/dev/null) | tr '\n' ' ')
  changed=${changed% } added=${added% }
  if [[ -z "$changed$added" ]]; then echo "NOTE  the lab/pam code here is the code this record ran (fingerprint matches)"
  else echo "NOTE  lab/pam changed since this record: changed ${changed:-none}; added ${added:-none} - the record proves the code it names, not this tree"; fi
}

# vault_api METHOD PATH [< JSON body] -> response body on stdout.
#   HTTP >= 400: Vault's own error text on stderr, return 1.
# The Vault HTTP API directly (not the CLI), as an onboarding pipeline would
# call it. The token goes to curl as a header FILE on a pipe (process
# substitution, -H @/dev/fd/N): it is never in curl's argv (`ps`), never in a
# temp file. Responses can carry passwords (static-cred), so they stay in
# shell variables and pipes, never on disk.
vault_api() {
  local method="$1" path="$2" resp code
  [[ -n "${VAULT_TOKEN:-}" ]] || die "vault_api: export VAULT_TOKEN first"
  if [[ "$method" == GET || "$method" == DELETE ]]; then
    resp=$(curl -sS -w '\n%{http_code}' -X "$method" -H @<(printf 'X-Vault-Token: %s\n' "$VAULT_TOKEN") \
      "$VAULT_HOST_ADDR/v1/$path" </dev/null) || return 1
  else
    resp=$(curl -sS -w '\n%{http_code}' -X "$method" -H @<(printf 'X-Vault-Token: %s\n' "$VAULT_TOKEN") \
      -H 'Content-Type: application/json' --data-binary @- "$VAULT_HOST_ADDR/v1/$path") || return 1
  fi
  code="${resp##*$'\n'}"
  resp="${resp%$'\n'*}"
  if [[ ! "$code" =~ ^[0-9]+$ || "$code" -ge 400 ]]; then
    printf 'vault %s %s -> HTTP %s: %s\n' "$method" "$path" "$code" \
      "$(printf '%s' "$resp" | jq -r '(.errors // []) | join("; ")' 2>/dev/null || true)" >&2
    return 1
  fi
  printf '%s' "$resp"
}

vault_list() { # vault_list PATH -> keys, one per line ('' when the path is empty / missing)
  { vault_api GET "${1%/}/?list=true" 2>/dev/null || true; } | jq -r '.data.keys[]?' 2>/dev/null || true
}

static_roles() { # every LDAP static role, hierarchical names flattened: svc-backup, svc/svc-sql01, ...
  local prefix="${1:-}" k
  for k in $(vault_list "ldap/static-role/$prefix"); do
    if [[ "$k" == */ ]]; then static_roles "$prefix$k"; else printf '%s\n' "$prefix$k"; fi
  done
}

