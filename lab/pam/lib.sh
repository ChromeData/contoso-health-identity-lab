need() { command -v "$1" >/dev/null 2>&1 || { echo "missing dependency: $1" >&2; exit 1; }; }
log()  { printf '[%s] %s\n' "$(date -u +%H:%M:%SZ)" "$*"; }
die()  { echo "ERROR: $*" >&2; exit 1; }

# shellcheck source=/dev/null  # .env is generated by pam-up.sh and gitignored
load_env() {
  local f="$ENV_FILE"
  [[ -f "$f" ]] || die "$f missing - run ./pam-up.sh first"
  [[ "$f" == /* ]] || f="./$f"
  set -a; . "$f"; set +a
}

set_env() { # set_env KEY VALUE  (idempotent edit of .env)
  local k="$1" v="$2"
  if grep -q "^${k}=" .env; then
    sed -i.bak "s|^${k}=.*|${k}=${v}|" .env && rm -f .env.bak
  else
    echo "${k}=${v}" >> .env
  fi
}

# Run the vault CLI inside the container. `-e VAULT_TOKEN` (no `=value`)
# forwards the caller's exported token from the environment, so the token
# never appears in docker's argument list (visible in `ps`). Unset -> no token.
vault_cli() { docker compose exec -T -e VAULT_TOKEN vault vault "$@"; }

root_token() { jq -r '.root_token' "$VAULT_INIT_FILE"; }

vault_wait() {
  for _ in $(seq 1 30); do
    # The container must be running (not restarting) before its CLI answers.
    if [[ "$(docker compose ps vault --format '{{.State}}' 2>/dev/null)" != "running" ]]; then sleep 2; continue; fi
    # `vault status` exits 0 (unsealed), 2 (sealed) or 1 (error/unreachable).
    local rc=0; vault_cli status >/dev/null 2>&1 || rc=$?
    [[ $rc -ne 1 ]] && return 0
    sleep 2
  done
  die "Vault did not come up (docker compose logs vault)"
}

vault_unseal() {
  vault_wait
  local sealed
  sealed=$(vault_cli status -format=json 2>/dev/null | jq -r '.sealed' || true)
  if [[ "$sealed" == "true" ]]; then
    log "Unsealing Vault"
    # Unseal over the HTTP API with the key piped as the request body: the key
    # never appears in a process argument list (the CLI has no stdin form).
    jq -c '{key: .unseal_keys_b64[0]}' "$VAULT_INIT_FILE" \
      | curl -fsS -X PUT --data @- "$VAULT_HOST_ADDR/v1/sys/unseal" \
      | jq -e '.sealed == false' >/dev/null || die "Vault unseal failed"
  fi
}

guac_token() { # printf '%s' PASSWORD | guac_token USER -> prints authToken
  # Password read from stdin (password@-), never placed on curl's command line.
  curl -fsS -X POST "$GUAC_URL/api/tokens" \
    --data-urlencode "username=$1" --data-urlencode "password@-" | jq -r '.authToken'
}

guac_admin_token() { guac_token guacadmin < .secrets/guacadmin-password; }

# One recorded RDP connection per Tier-0 account, so two concurrent check-outs
# never overwrite each other's injected credential.
conn_name() { printf 'DC01 - %s (recorded)' "$1"; }

# RDP targets psm-session.sh can broker a Tier-0 session to (--target):
#   dc01        DC01, the Windows Server DC (DC_PUBLIC_IP:3389, NLA, domain
#               NETBIOS). The real target; needs the Azure lab.
#   rdp-target  STAND-IN, harness only: a Linux container running xrdp
#               (rdp-target/, compose profile "rdp") that authenticates the
#               same AD account by Kerberos against the Samba AD DC. It stands
#               in for an RDP session to DC01 so the brokered, recorded RDP
#               path runs without a tenant. Not Windows: TLS, no NLA, an xterm
#               instead of a desktop.
rdp_target_ok() { [[ "$1" == dc01 || "$1" == rdp-target ]]; }
rdp_conn_name() { # rdp_conn_name TARGET ACCOUNT -> the Guacamole connection's name
  case "$1" in
    dc01) conn_name "$2" ;;
    rdp-target) printf 'RDP-TARGET (Linux xrdp stand-in for DC01) - %s (recorded)' "$2" ;;
    *) die "unknown RDP target '$1' (dc01 | rdp-target)" ;;
  esac
}

guac_conn_id() { # guac_conn_id TOKEN NAME -> connection identifier ('' if none)
  curl -fsS -H "Guacamole-Token: $1" "$GUAC_URL/api/session/data/postgresql/connections" \
    | jq -r --arg n "$2" 'to_entries[] | select(.value.name==$n) | .key' | head -1
}

# --- AD onboarding (shared by vault-onboard-ad.sh and test/e2e.sh) -----------
# Azure-specific discovery (az vm show, run-command, Key Vault) stays in
# vault-onboard-ad.sh; everything below also runs in the Samba AD harness, so
# the harness tests this exact code.

vault_install_ca() { # vault_install_ca < ca.pem   -> .secrets/vault-ca/ad-root-ca.pem ($CA_FILE)
  local dst="$CA_FILE" dir
  dir=$(dirname "$CA_FILE")
  mkdir -p "$dir"
  # tr: run-command output from Windows PowerShell has CRLF line endings.
  tr -d '\r' | sed -n '/-----BEGIN CERTIFICATE-----/,/-----END CERTIFICATE-----/p' > "$dst"
  grep -q 'BEGIN CERTIFICATE' "$dst" || die "CA certificate not returned"
  openssl x509 -noout -in "$dst" 2>/dev/null || die "CA certificate does not parse (openssl x509)"
  # Public material only: readable by the vault container user (uid 100) also
  # where the bind mount keeps host ownership and modes (native Linux Docker).
  chmod 755 "$dir" && chmod 644 "$dst"
}

vault_point_at_dc() { # vault_point_at_dc DC_FQDN DC_IP   -> .env, recreate + unseal
  set_env DC_FQDN "$1"
  set_env DC_PUBLIC_IP "$2"
  # Exported as well: a DC_FQDN/DC_PUBLIC_IP already in the environment (e.g.
  # from load_env) would otherwise beat .env when compose fills extra_hosts.
  export DC_FQDN="$1" DC_PUBLIC_IP="$2"
  if [[ -n "$1" ]]; then
    log "Recreating the Vault container ($1 -> $2 host mapping + CA)"
  else
    log "Recreating the Vault container (DC host mapping cleared)"
  fi
  docker compose up -d --force-recreate vault >/dev/null
  vault_unseal
}

# vault_configure_ad BASE_DN DC_FQDN [--keep-bindpass]   (root VAULT_TOKEN exported)
#   Bind password on stdin. --keep-bindpass (re-run against the SAME DC):
#   stdin is not read and Vault keeps its current bind password - after
#   --rotate-root only Vault knows it, and writing the stale Key Vault copy
#   back would lock Vault out of AD (verified on Vault 2.1.1 against Samba).
#   * LDAP secrets engine -> ldaps://DC_FQDN, verified against the AD root CA
#     (vault_install_ca; no insecure_tls), bound as svc-vault-rotator.
#   * STATIC role  svc-backup          -> rotated now, then every 24h   (CPM)
#   * LIBRARY set  tier0-admin-01/02   -> exclusive check-out, 1h TTL,
#                                         password rotated on every check-in
#   * Policy tier0-checkout             -> least-privilege token for psm-session.sh
#   Re-running is idempotent: re-writing an existing static role or library
#   set does NOT rotate again (only creating one does).
vault_configure_ad() {
  local base_dn="$1" dc_fqdn="$2" keep="${3:-}" bindpass=""
  [[ -n "$base_dn" && -n "$dc_fqdn" ]] || die "usage: vault_configure_ad BASE_DN DC_FQDN [--keep-bindpass] < bind-password"
  [[ -n "${VAULT_TOKEN:-}" ]] || die "vault_configure_ad: export a root VAULT_TOKEN first"
  [[ -s "$CA_FILE" ]] || die "no AD root CA - run vault_install_ca first"
  if [[ "$keep" == --keep-bindpass ]]; then
    vault_cli read ldap/config >/dev/null 2>&1 || die "--keep-bindpass: ldap/ is not configured yet"
  else
    [[ -t 0 ]] && die "vault_configure_ad: pipe the bind password on stdin"
    # Read it up front: if the producer (az keyvault ...) failed, stop here
    # instead of configuring Vault with an empty bind password.
    bindpass=$(tr -d '\r\n')
    [[ -n "$bindpass" ]] || die "vault_configure_ad: empty bind password on stdin"
  fi

  if ! vault_cli secrets list -format=json | jq -e 'has("ldap/")' >/dev/null; then
    vault_cli secrets enable ldap >/dev/null
  fi

  # schema=ad: Vault writes unicodePwd, which AD accepts only over an encrypted
  # connection - hence ldaps:// and the CA. userattr: with schema=ad Vault
  # defaults to userPrincipalName, but the library names accounts by logon
  # name (tier0-admin-01), so match them on sAMAccountName instead.
  local cfg=(
    binddn="CN=svc-vault-rotator,OU=ServiceAccounts,${base_dn}"
    url="ldaps://${dc_fqdn}"
    certificate=@/vault/ca/ad-root-ca.pem
    schema=ad
    userdn="${base_dn}"
    userattr=sAMAccountName
  )
  if [[ -n "$bindpass" ]]; then
    log "Configuring LDAP secrets engine (bind: svc-vault-rotator, password via stdin)"
    printf '%s' "$bindpass" | vault_cli write ldap/config bindpass=- "${cfg[@]}" >/dev/null
    bindpass=""
  else
    # Omitting bindpass on an update leaves Vault's stored one untouched.
    log "Updating LDAP secrets engine - keeping Vault's current bind password"
    vault_cli write ldap/config "${cfg[@]}" </dev/null >/dev/null
  fi

  if vault_cli read ldap/static-role/svc-backup >/dev/null 2>&1; then
    log "Static role svc-backup exists - updated, not re-rotated (24h schedule continues)"
  else
    log "Static role svc-backup (rotates now, on onboarding, then every 24h)"
  fi
  vault_cli write ldap/static-role/svc-backup \
    dn="CN=svc-backup,OU=ServiceAccounts,${base_dn}" \
    username=svc-backup rotation_period=24h >/dev/null

  log "Library set tier0-admins (exclusive check-out, rotate on check-in)"
  vault_cli write ldap/library/tier0-admins \
    service_account_names="tier0-admin-01,tier0-admin-02" \
    ttl=1h max_ttl=4h disable_check_in_enforcement=false >/dev/null

  log "Policy tier0-checkout (least privilege for the session broker)"
  vault_cli policy write tier0-checkout - >/dev/null <<'HCL'
# Check out / check in a Tier-0 admin from the library - nothing else.
path "ldap/library/tier0-admins/check-out" { capabilities = ["update"] }
path "ldap/library/tier0-admins/check-in"  { capabilities = ["update"] }
path "ldap/library/tier0-admins/status"    { capabilities = ["read"] }
HCL

  # Proof (metadata only - no passwords printed)
  log "svc-backup last rotated: $(vault_cli read -field=last_vault_rotation ldap/static-cred/svc-backup)"
  vault_cli read -format=json ldap/library/tier0-admins/status \
    | jq -r '.data | to_entries[] | "  \(.key): available=\(.value.available)"'
}

vault_rotate_root() { # Vault resets its OWN bind password; afterwards only Vault knows it
  log "Rotating the bind (reconcile) password - only Vault will know it from now on"
  vault_cli write -f ldap/rotate-root >/dev/null
}

