library_members() { # library_members SET -> its service_account_names, one per line
  { vault_api GET "ldap/library/$1" 2>/dev/null || true; } | jq -r '.data.service_account_names[]?' 2>/dev/null || true
}

# static_role_index -> "username(lowercase)<TAB>role path" for every static
# role: one LIST pass + one GET per role. A caller that looks up MANY
# accounts (onboard.sh) builds it once and looks up locally: asking Vault per
# account is O(accounts x roles) - at 500 accounts an onboarding re-run spent
# almost all of its time there (test/e2e-scale.sh measured it).
static_role_index() {
  local r
  while IFS= read -r r; do
    [[ -n "$r" ]] || continue
    vault_api GET "ldap/static-role/$r" | jq -r --arg p "$r" '"\(.data.username | ascii_downcase)\t\($p)"'
  done < <(static_roles)
}

static_role_of() { # static_role_of SAM -> the static role path managing it ('' if none)
  # Fast path for ONE account (rotate.sh): the names roles get here -
  # <tier static_prefix>/<sam> (onboard.sh) or flat <sam> (vault-onboard-ad.sh)
  # - each confirmed by the role's username. Then the full scan, so a role
  # made by hand under any other name is still found.
  local r p want
  want=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')
  for p in $(jq -r '[.tiers[].static_prefix // empty] | unique[]' "$POLICY_FILE" 2>/dev/null || true) ""; do
    r="${p:+$p/}$1"
    if [[ "$({ vault_api GET "ldap/static-role/$r" 2>/dev/null || true; } | jq -r '.data.username // "" | ascii_downcase')" == "$want" ]]; then
      printf '%s\n' "$r"; return 0
    fi
  done
  while IFS= read -r r; do
    [[ -n "$r" ]] || continue
    if [[ "$(vault_api GET "ldap/static-role/$r" | jq -r '.data.username | ascii_downcase')" == "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" ]]; then
      printf '%s\n' "$r"; return 0
    fi
  done < <(static_roles)
}

policy_tier() { # policy_tier TIER KEY -> value from pam-policy.json ('' if unset)
  jq -r --arg t "$1" --arg k "$2" '.tiers[$t][$k] // empty' "$POLICY_FILE"
}

# policy_flag TIER KEY -> prints "true" or "false"; anything else is an error.
# For the GATES (require_ticket, dependency_check) a missing key, a renamed
# tier or a broken pam-policy.json must never read as "off": `[[ "$(policy_tier
# ...)" == true ]]` would silently skip the gate on all three. So this fails
# CLOSED: only an explicit JSON `false` turns a gate off.
# Call it as `v=$(policy_flag T K) || exit 1` - a `die` inside a command
# substitution only ends the subshell, which is how gates fail open.
policy_flag() {
  local v
  v=$(jq -er --arg t "$1" --arg k "$2" '
        if (.tiers[$t] | type) != "object" then error("no tier \($t)")
        elif (.tiers[$t][$k] | type) != "boolean" then error("\($k) is not true/false")
        else .tiers[$t][$k] | tostring end' "$POLICY_FILE" 2>/dev/null) \
    || { echo "ERROR: $POLICY_FILE: tiers.$1.$2 must be true or false (missing, mistyped or unreadable) - refusing to guess, the gate stays ON" >&2; return 1; }
  printf '%s' "$v"
}

# policy_count TIER KEY -> a whole number >= 1 (e.g. approvals_required).
# Same fail-closed rule as policy_flag: a missing key, a string, 0, a fraction
# or a broken file is an error, never "no approval needed". Call it as
# `n=$(policy_count T K) || exit 1`.
policy_count() {
  local v
  v=$(jq -er --arg t "$1" --arg k "$2" '
        if (.tiers[$t] | type) != "object" then error("no tier \($t)")
        elif (.tiers[$t][$k] | type) != "number" then error("\($k) is not a number")
        elif .tiers[$t][$k] < 1 or (.tiers[$t][$k] | floor) != .tiers[$t][$k] then error("\($k) is not a whole number >= 1")
        else .tiers[$t][$k] | tostring end' "$POLICY_FILE" 2>/dev/null) \
    || { echo "ERROR: $POLICY_FILE: tiers.$1.$2 must be a whole number >= 1 (missing, mistyped or unreadable) - refusing to guess, the gate stays ON" >&2; return 1; }
  printf '%s' "$v"
}

# --- dependency gate ("usages" must be handled before a password change) ------
# dep_gate SAM DEPS_FILE
#   0  every dependency recorded for SAM is resolved (or the list is empty)
#   1  unresolved dependencies (one per line on stdout)
#   2  no record at all for SAM: unknown is NOT "none" - rotating a service
#      account nobody has looked at is how outages start
# "resolved" means the consumer (Windows service, scheduled task, app pool,
# connection string) fetches the password from Vault at run time, or was
# decommissioned. Vault rotates static roles on its own schedule without
# asking anyone, so this gate sits where a human starts a rotation:
# onboarding (creating a static role rotates immediately) and rotate.sh.
dep_gate() {
  local sam f="$2" unresolved
  sam=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')
  [[ -s "$f" ]] || { echo "dependency map $f is missing"; return 2; }
  jq -e --arg a "$sam" '.accounts | with_entries(.key |= ascii_downcase) | has($a)' "$f" >/dev/null \
    || { echo "no dependency record for $1 in $f (add one; an empty list [] means 'no consumers')"; return 2; }
  unresolved=$(jq -r --arg a "$sam" '.accounts | with_entries(.key |= ascii_downcase) | .[$a][]
      | select(.resolved != true) | "\(.type) \(.name) on \(.host) (owner: \(.owner // "unknown"))"' "$f")
  [[ -z "$unresolved" ]] && return 0
  printf '%s\n' "$unresolved"
  return 1
}

# A forced override needs a reason a reviewer can follow: at least 20
# characters and a change number, so the exception register links to the
# change that accepted the outage risk.
check_justification() {
  local j="$1"
  [[ ${#j} -ge 20 ]] || die "--justification must be at least 20 characters"
  [[ "$j" =~ CHG[0-9]{7} ]] || die "--justification must reference a change number (CHG + 7 digits)"
}

# Exception register in Vault (KV v2 mount pam-meta): versioned, and every
# write lands in Vault's audit log with the token that made it.
pam_meta_enable() { # needs a root/admin VAULT_TOKEN
  vault_api GET sys/mounts | jq -e 'has("pam-meta/")' >/dev/null \
    || jq -n '{type: "kv", options: {version: "2"}, description: "PAM exception register (forced rotations, held-back accounts)"}' \
       | vault_api POST sys/mounts/pam-meta >/dev/null
}

record_override() { # record_override SAM ACTION JUSTIFICATION OPERATOR UNRESOLVED(multi-line)
  pam_meta_enable
  jq -n --arg s "$1" --arg a "$2" --arg j "$3" --arg o "$4" --arg u "$5" --arg t "$(date -u +%FT%TZ)" \
    '{data: {account: $s, action: $a, justification: $j, operator: $o, at: $t,
             unresolved_dependencies: ($u | split("\n") | map(select(length > 0)))}}' \
    | vault_api POST "pam-meta/data/exceptions/$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" >/dev/null
}

# --- ITSM ticket validation (ServiceNow Table API v2) + dual control ----------
# itsm_validate TICKET OPERATOR TIER SAFE -> 0 and TWO lines on stdout:
#   1. a one-line summary for the log
#   2. the approvers that counted, comma-separated (for the audit line and the
#      check-out token's metadata)
# or die with the specific reason. A ticket opens a check-out only if it is a
# change request that is APPROVED, in state Implement (-1), inside its planned
# window (UTC), ASSIGNED TO THE OPERATOR asking (no borrowing a colleague's
# change) and carries enough APPROVALS:
#
# Dual control (access approval with a minimum number of approvers; in the
# Microsoft design, ADR 0036, a PIM activation approval). The approvals are ServiceNow's own
# records, table sysapproval_approver (one row per approver per change). One
# counts only if it is
#   * in state "approved" (requested / rejected / cancelled ones do not),
#   * from someone who is NOT the requester: neither the operator asking for
#     the account nor the change's requested_by (no self-approval),
#   * from an authorised approver for SAFE: operators.json lists SAFE in that
#     person's `approves` (the permission to authorise
#     account requests),
# and each person counts once. pam-policy.json tiers.<TIER>.approvals_required
# is the number of distinct approvals the tier needs: tier0 2 (two people,
# neither of them the requester), tier1 1. A missing, zero or mistyped value
# stops the check-out (policy_count: fail closed), and so does a rejection by
# anyone on the change, or an approvals table ITSM cannot serve.
#
# Credentials: ITSM_USER in .env, password in $ITSM_PASSWORD_FILE
# (.secrets/itsm-password), handed to curl as a config file on stdin (never
# argv). verify: ServiceNow change_request state values (-1 = Implement); the
# dot-walked fields assigned_to.user_name / requested_by.user_name in
# sysparm_fields; the sysapproval_approver query on the dot-walked
# sysapproval.number and that table's state values (requested, approved,
# rejected, cancelled, not requested, not_required).
#
# NB: bash 3.2 clears `set -e` inside command substitutions and callers run
# this as out=$(itsm_validate ...), so every failure below is an explicit die.

# itsm_get TABLE QUERY FIELDS LIMIT -> the Table API v2 response body (JSON).
# Non-zero, with the reason on stderr, on a transport error, a non-200 answer
# or a body without a result list.
itsm_get() {
  local pw resp code
  pw=$(tr -d '\r\n' < "$ITSM_PASSWORD_FILE") || { echo "ERROR: cannot read $ITSM_PASSWORD_FILE" >&2; return 1; }
  pw="${pw//\\/\\\\}"; pw="${pw//\"/\\\"}"
  resp=$(printf 'user = "%s:%s"\n' "$ITSM_USER" "$pw" | curl -sS -K - -G -w '\n%{http_code}' \
    -H 'Accept: application/json' "${ITSM_URL%/}/api/now/v2/table/$1" \
    --data-urlencode "sysparm_query=$2" --data-urlencode "sysparm_fields=$3" \
    --data-urlencode "sysparm_limit=$4" --data-urlencode 'sysparm_display_value=false' \
    --data-urlencode 'sysparm_exclude_reference_link=true') \
    || { pw=""; echo "ERROR: ITSM unreachable at $ITSM_URL" >&2; return 1; }
  pw=""
  code="${resp##*$'\n'}"; resp="${resp%$'\n'*}"
  [[ "$code" == 200 ]] || { echo "ERROR: ITSM lookup of $1 ($2) failed (HTTP $code)" >&2; return 1; }
  printf '%s' "$resp" | jq -e '.result | type == "array"' >/dev/null 2>&1 \
    || { echo "ERROR: ITSM lookup of $1 ($2) returned no result list" >&2; return 1; }
  printf '%s' "$resp"
}

itsm_validate() {
  local t="$1" op="$2" tier="${3:-}" safe="${4:-}" need resp rec approval state start end who reqby now verdict
  local rejected counted have notes rule
  [[ "$t" =~ ^CHG[0-9]{7}$ ]] || die "ticket '$t' is not a change number (CHG + 7 digits)"
  [[ -n "$tier" && -n "$safe" ]] || die "itsm_validate needs TICKET OPERATOR TIER SAFE (the approval rule depends on the tier)"
  [[ -s "$ITSM_PASSWORD_FILE" && -n "${ITSM_URL:-}" && -n "${ITSM_USER:-}" ]] || die "ITSM not configured (ITSM_URL/ITSM_USER in .env, $ITSM_PASSWORD_FILE) - run ./pam-up.sh"
  need=$(policy_count "$tier" approvals_required) || exit 1
  resp=$(itsm_get change_request "number=$t" \
    'number,state,approval,start_date,end_date,assigned_to.user_name,requested_by.user_name,short_description' 1) || exit 1
  rec=$(printf '%s' "$resp" | jq -c '.result[0] // empty')
  [[ -n "$rec" ]] || die "ticket $t not found in ITSM"
  approval=$(printf '%s' "$rec" | jq -r '.approval // ""')
  state=$(printf '%s' "$rec" | jq -r '.state // ""')
  start=$(printf '%s' "$rec" | jq -r '.start_date // ""')
  end=$(printf '%s' "$rec" | jq -r '.end_date // ""')
  who=$(printf '%s' "$rec" | jq -r '."assigned_to.user_name" // ""')
  reqby=$(printf '%s' "$rec" | jq -r '."requested_by.user_name" // ""')
  now=$(date -u '+%Y-%m-%d %H:%M:%S')
  [[ "$approval" == approved ]] || die "ticket $t is not approved (approval=${approval:-empty})"
  [[ "$state" == "-1" ]] || die "ticket $t is not in Implement (state=${state:-empty})"
  [[ -n "$start" && -n "$end" ]] || die "ticket $t has no planned window"
  if [[ "$now" < "$start" || "$now" > "$end" ]]; then
    die "ticket $t is outside its window ($start - $end UTC, now $now)"
  fi
  [[ "$who" == "$op" ]] || die "ticket $t is assigned to '${who:-nobody}', not $op"

  # Dual control: who approved this change, and which of those approvals count.
  resp=$(itsm_get sysapproval_approver "sysapproval.number=$t" 'approver.user_name,state' 100) \
    || die "ticket $t: its approval records could not be read - no check-out without them"
  verdict=$(printf '%s' "$resp" | jq -c --arg op "$op" --arg rb "$reqby" --arg safe "$safe" --slurpfile ops "$OPERATORS_FILE" '
      ($ops[0].operators // {}) as $o
      | [.result[] | {who: (."approver.user_name" // ""), state: (.state // "")} | select(.who != "")] as $rows
      | ([$rows[] | select(.state == "rejected") | .who] | unique) as $rejected
      | ([$rows[] | select(.state == "approved") | .who] | unique) as $approved
      | [$approved[] | select(. == $op or ($rb != "" and . == $rb))] as $self
      | [$approved[] | . as $w | select(($self | index($w)) == null)
                     | select((($o[$w].approves // []) | index($safe)) == null)] as $unauth
      | {rejected: $rejected,
         self: [$self[] | if . == $op then "\(.) (self-approval: the operator asking)" else "\(.) (self-approval: the change'"'"'s requester)" end],
         unauthorized: [$unauth[] | "\(.) (not an authorized approver for \($safe))"],
         counted: [$approved[] | . as $w | select((($self + $unauth) | index($w)) == null)]}') \
    || die "ticket $t: its approval records could not be parsed - no check-out"
  rejected=$(printf '%s' "$verdict" | jq -r '.rejected | join(", ")')
  [[ -z "$rejected" ]] || die "ticket $t was rejected by $rejected - a rejection stops the check-out"
  counted=$(printf '%s' "$verdict" | jq -r '.counted | join(",")')
  have=$(printf '%s' "$verdict" | jq -r '.counted | length')
  [[ "$have" =~ ^[0-9]+$ ]] || die "ticket $t: could not count its approvals"
  if [[ "$need" -ge 2 ]]; then rule="dual control: $need distinct approvers, none of them the requester"
  else rule="$need approver, not the requester"; fi
  if [[ "$have" -lt "$need" ]]; then
    notes=$(printf '%s' "$verdict" | jq -r '(.self + .unauthorized) | join("; ")')
    die "ticket $t has $have of $need required approvals ($tier $rule)${notes:+ - not counted: $notes}"
  fi
  printf '%s approved, Implement, window %s - %s UTC, assigned to %s; approved by %s (%s of %s required: %s)\n' \
    "$t" "$start" "$end" "$who" "${counted//,/ + }" "$have" "$need" "$rule"
  printf '%s\n' "$counted"
}

# --- operators (who may check out what) ---------------------------------------
# operators.json says which person may check out from which library set /
# sign with which SSH role. A name not listed gets nothing.
operator_allowed() { # operator_allowed NAME KIND(libraries|ssh_roles) ITEM
  # Lab names (ops-alice) or, at tenant time, Entra UPNs (alice@contoso...):
  # the name Guacamole's OIDC extension takes from the token must match.
  [[ "$1" =~ ^[a-z][a-z0-9._@-]{1,63}$ ]] || die "operator name '$1' is invalid (lowercase, 2-64 chars: a-z 0-9 . _ @ -)"
  jq -e --arg o "$1" '.operators | has($o)' "$OPERATORS_FILE" >/dev/null || die "operator $1 is not in $OPERATORS_FILE"
  jq -e --arg o "$1" --arg k "$2" --arg i "$3" '.operators[$o][$k] // [] | index($i) != null' "$OPERATORS_FILE" >/dev/null \
    || die "operator $1 is not a member of $3 ($2 in $OPERATORS_FILE)"
}

operator_pw_file() { printf '.secrets/operators/%s-password' "$1"; }

guac_user_exists() { # guac_user_exists TOKEN NAME -> 0 exists, 1 not; any other answer stops the script
  local code
  code=$(curl -sS -o /dev/null -w '%{http_code}' -H "Guacamole-Token: $1" \
    "$GUAC_URL/api/session/data/postgresql/users/$2") || true
  case "$code" in
    200) return 0 ;;
    404) return 1 ;;
    *)   die "Guacamole user lookup for $2 failed (HTTP ${code:-none})" ;;
  esac
}

# --- operator sign-in mode -----------------------------------------------------
# LAB mode (default): each operator gets a local Guacamole password in
# .secrets/operators/<name>-password (0600) - there is no IdP on a laptop.
# OIDC mode (tenant time, docker-compose.oidc.yml): people sign in through
# Entra ID, so MFA, Conditional Access and the phishing-resistant strength
# apply. In that mode NO operator may keep a working local password: the
# local login form stays on the page for guacadmin (break-glass + History
# playback) and /api/tokens accepts database credentials whatever the UI
# shows, so any operator's local password would be a way around Entra MFA
# and CA - and the broker host would hold all of them.
# On: PAM_OIDC=1, or OIDC_CLIENT_ID set in .env (the overlay cannot start
# without it, so a configured overlay never falls back to lab mode).
pam_oidc_mode() { [[ "${PAM_OIDC:-0}" == 1 || -n "${OIDC_CLIENT_ID:-}" ]]; }

guac_user_record() { # guac_user_record TOKEN NAME -> the user's JSON (username + attributes)
  curl -fsS -H "Guacamole-Token: $1" "$GUAC_URL/api/session/data/postgresql/users/$2"
}

# guac_put_password TOKEN NAME < PASSWORD: replace NAME's local password and
# KEEP its attributes. Guacamole's PUT replaces the whole record, so a body
# with `attributes: {}` would clear e.g. a "disabled" flag an admin set.
# Password: stdin -> jq (-Rs) -> curl body on stdin (-d @-), never in argv.
guac_put_password() {
  local rec
  rec=$(guac_user_record "$1" "$2") || return 1
  jq -Rs --argjson rec "$rec" '{username: $rec.username, password: ., attributes: ($rec.attributes // {})}' \
    | curl -fsS -X PUT -H "Guacamole-Token: $1" -H 'Content-Type: application/json' \
        "$GUAC_URL/api/session/data/postgresql/users/$2" -d @- >/dev/null
}

# ensure_guac_operator NAME: a per-person Guacamole user with NO system
# permissions.
#   lab mode : created on first use with a local password in .secrets/operators/.
#   OIDC mode: NEVER creates a user and never leaves a usable password. The
#              record must already exist (POSTGRESQL_AUTO_CREATE_ACCOUNTS makes
#              it on the person's first Entra sign-in), else "sign in through
#              Entra first". Any local password on it (a lab leftover, or one
#              an admin typed in) is overwritten with a random value that is
#              never stored, and the lab password file is deleted: the SSO
#              path is the only way in. verify: whether a Guacamole 1.6
#              auto-created record has a usable password at all (if not, the
#              overwrite is belt-and-braces).
ensure_guac_operator() {
  local op="$1" tok tmp pwf
  [[ "$op" != guacadmin ]] || die "guacadmin is the break-glass admin, not an operator"
  pwf=$(operator_pw_file "$op")
  mkdir -p .secrets/operators && chmod 700 .secrets/operators
  tok=$(guac_admin_token)
  if pam_oidc_mode; then
    guac_user_exists "$tok" "$op" \
      || die "Guacamole has no user $op - in OIDC mode $op must sign in through Entra first (that creates the record); no local user is made"
    openssl rand -hex 32 | guac_put_password "$tok" "$op" \
      || die "could not clear $op's local Guacamole password"
    rm -f "$pwf"
    log "Guacamole user $op (OIDC mode): local password replaced by an unusable random value (not stored) - Entra sign-in only"
    return 0
  fi
  if guac_user_exists "$tok" "$op"; then
    [[ -s "$pwf" ]] && return 0
    tmp=$(mktemp "$pwf.XXXXXX")
    printf 'Gx-%s' "$(openssl rand -hex 16)" > "$tmp"
    guac_put_password "$tok" "$op" < "$tmp" || { rm -f "$tmp"; die "could not reset Guacamole user $op's password"; }
  else
    tmp=$(mktemp "$pwf.XXXXXX")
    printf 'Gx-%s' "$(openssl rand -hex 16)" > "$tmp"
    jq -Rs --arg u "$op" '{username: $u, password: ., attributes: {}}' < "$tmp" \
      | curl -fsS -X POST -H "Guacamole-Token: $tok" -H 'Content-Type: application/json' \
          "$GUAC_URL/api/session/data/postgresql/users" -d @- >/dev/null \
      || { rm -f "$tmp"; die "could not set up Guacamole user $op"; }
  fi
  mv "$tmp" "$pwf"
  log "Guacamole user $op ready (no system permissions) - password in $pwf, not displayed"
}

operator_signin_hint() { # operator_signin_hint NAME -> one log line: how NAME signs in
  if pam_oidc_mode; then
    printf '%s signs in to %s with Entra ID (SSO link: MFA + Conditional Access)' "$1" "$GUAC_URL"
  else
    printf '%s signs in to %s (lab password in %s)' "$1" "$GUAC_URL" "$(operator_pw_file "$1")"
  fi
}

# guac_grant OPERATOR CONN_ID add|remove: READ (see + connect) on ONE
# connection. Reading its parameters (the injected secret) would need
# UPDATE or ADMINISTER, which nobody but guacadmin holds. After an add, the
# operator's EFFECTIVE permissions are checked, not assumed.
guac_grant() {
  local op="$1" id="$2" what="$3" tok
  tok=$(guac_admin_token)
  if [[ "$what" == remove ]] && ! guac_user_exists "$tok" "$op"; then return 0; fi
  jq -n --arg o "$what" --arg id "$id" '[{op: $o, path: ("/connectionPermissions/" + $id), value: "READ"}]' \
    | curl -fsS -X PATCH -H "Guacamole-Token: $tok" -H 'Content-Type: application/json' \
        "$GUAC_URL/api/session/data/postgresql/users/$op/permissions" -d @- >/dev/null \
    || die "could not $what $op's READ on connection $id"
  [[ "$what" == add ]] || return 0
  curl -fsS -H "Guacamole-Token: $tok" "$GUAC_URL/api/session/data/postgresql/users/$op/effectivePermissions" \
    | jq -e --arg id "$id" '.systemPermissions == [] and .connectionPermissions[$id] == ["READ"]' >/dev/null \
    || die "$op must hold READ only on connection $id and no system permissions - fix its rights in Guacamole"
}

# One audit line per privileged-access event, JSON, append-only file in $OUT/
# (the SIEM-forwardable shape), AND printed. Names who, what, which ticket.
audit_line() { # audit_line EVENT key=value...
  local ev="$1" kv json; shift
  json=$(jq -nc --arg e "$ev" --arg t "$(date -u +%FT%TZ)" '{time: $t, event: $e}')
  for kv in "$@"; do json=$(printf '%s' "$json" | jq -c --arg k "${kv%%=*}" --arg v "${kv#*=}" '. + {($k): $v}'); done
  out_dir
  printf '%s\n' "$json" >> "$OUT/pam-audit.jsonl"
  log "AUDIT $ev $*"
}
