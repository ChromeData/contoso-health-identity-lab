#!/usr/bin/env bash
# =============================================================================
# pam-up.sh - start the PAM/IGA stand-ins and do every one-time init.
# Idempotent: safe to re-run (e.g. after a laptop restart, to unseal Vault).
#
#   1. .env with random credentials (never committed)
#   2. Guacamole DB schema
#   3. docker compose up
#   4. Vault: init (1 key share - LAB ONLY), unseal, file audit device
#   5. Guacamole: replace the default guacadmin/guacadmin password (re-checked
#      every run, so a reset guac-db is caught); retire the old shared
#      t0-operator user and shared broker token (sessions are per person
#      now: psm-session.sh --operator)
#   6. ITSM mock credentials + empty ticket store (ticket-gated check-out)
#
# Usage: ./pam-up.sh              everything above (the full stand-in stack)
#        ./pam-up.sh --midpoint   only steps 1 + 6 and midPoint with its
#                                 database (no Vault or Guacamole),
#                                 then WAIT until midPoint's REST API accepts
#                                 the administrator - ready for
#                                 midpoint/run-campaign.sh and
#                                 test/e2e-midpoint.sh. A first start takes
#                                 minutes. Safe on a running full stack (it
#                                 only starts what is missing, and waits).
# =============================================================================
source "$(dirname "$0")/lib.sh"
need docker; need jq; need openssl; need curl

MODE=all
case "${1:-}" in
  "") ;;
  --midpoint) MODE=midpoint ;;
  -h|--help) sed -n '/^# ====/,/^# ====/p' "$PAM_DIR/pam-up.sh" | sed '1d;$d'; exit 0 ;;
  *) die "usage: ./pam-up.sh [--midpoint]" ;;
esac
[[ $# -le 1 ]] || die "usage: ./pam-up.sh [--midpoint]"

mkdir -p .secrets/vault-ca && chmod 700 .secrets
# vault-ca holds only the AD root CA (public), bind-mounted into Vault: 755 so
# the container user can read it also where modes pass through (native Linux).
chmod 755 .secrets/vault-ca
# A zero-byte init file means an earlier init crashed half-way: discard it.
[[ -f .secrets/vault-init.json && ! -s .secrets/vault-init.json ]] && rm -f .secrets/vault-init.json

# 1. credentials --------------------------------------------------------------
if [[ ! -f .env ]]; then
  log "Generating .env (random credentials)"
  cat > .env <<ENV
GUAC_DB_PASSWORD=$(openssl rand -hex 24)
MIDPOINT_DB_PASSWORD=$(openssl rand -hex 24)
MIDPOINT_ADMIN_PASSWORD=Mp-$(openssl rand -hex 12)-9a
DC_FQDN=
DC_PUBLIC_IP=
ENV
fi

# 1b. ITSM (ticket validation for check-out). Added to an existing .env too,
#     so a stack created before this feature upgrades in place. ITSM_URL is
#     only set when absent: at tenant time it points at the ServiceNow PDI and
#     must not be reset to the mock. The mock gets only SHA-256("user:pw").
grep -q '^ITSM_URL=' .env || set_env ITSM_URL http://127.0.0.1:8084
grep -q '^ITSM_USER=' .env || set_env ITSM_USER pam-broker
if [[ ! -s .secrets/itsm-password ]]; then
  log "Generating the ITSM integration password (.secrets/itsm-password)"
  openssl rand -hex 24 > .secrets/itsm-password
fi
itsm_user=$(sed -n 's/^ITSM_USER=//p' .env)
# printf is a shell builtin: the password is not in any process's argv.
set_env ITSM_AUTH_SHA256 "$(printf '%s:%s' "$itsm_user" "$(tr -d '\r\n' < .secrets/itsm-password)" | openssl dgst -sha256 -r | cut -d' ' -f1)"
# The mock (uid 10001) reads tickets from here; public lab data, 755/644.
mkdir -p itsm/data && chmod 755 itsm itsm/data
[[ -f itsm/data/tickets.json ]] || { echo '[]' > itsm/data/tickets.json; chmod 644 itsm/data/tickets.json; }

# --midpoint: the certification campaign needs midPoint only. compose still
# interpolates the whole file, which is why steps 1 + 1b ran (every
# ${VAR:?} the services require is in .env now); nothing else is started.
if [[ $MODE == midpoint ]]; then
  log "Starting midPoint only (midpoint-db -> midpoint-init -> midpoint)"
  docker compose up -d midpoint 2>&1 | { grep -v -e '^ Container' -e '^ Network' -e '^ Volume' || true; }
  # shellcheck source=midpoint/lib-midpoint.sh
  source "$PAM_DIR/midpoint/lib-midpoint.sh"
  mp_load_password
  log "Waiting for midPoint's REST API (first start: a few minutes)"
  mp_wait_up
  cat <<MSG

midPoint is up (loopback only):
  midPoint    $MP_URL   administrator / \$MIDPOINT_ADMIN_PASSWORD in .env
Next: midpoint/run-campaign.sh   (evidence -> lab/evidence/midpoint/<UTC>/)
      test/e2e-midpoint.sh       (two runs + assertions; test output in out/e2e/midpoint/)
MSG
  exit 0
fi

# 2. Guacamole schema (generated by the image itself, so it always matches) ----
if [[ ! -s guacamole/initdb.sql ]]; then
  log "Generating Guacamole PostgreSQL schema"
  # guacamole/ is not in a clone (git keeps no empty dirs; initdb.sql is
  # gitignored). 755, not the umask's 700: it holds only the public schema.
  mkdir -p guacamole && chmod 755 guacamole
  # Temp file + mv: a failed run must not leave a partial schema behind.
  tmp=$(mktemp guacamole/initdb.XXXXXX)
  docker run --rm guacamole/guacamole:1.6.0 /opt/guacamole/bin/initdb.sh --postgresql > "$tmp" \
    || { rm -f "$tmp"; die "could not generate the Guacamole schema"; }
  # 644, not the umask's 600: postgres (uid 999) reads it from the bind mount
  # during initdb, and on native Linux Docker a 0600 file of yours is
  # unreadable to it -> no schema, no Guacamole. Public schema, no secrets.
  chmod 644 "$tmp" && mv "$tmp" guacamole/initdb.sql
fi

# 3. up -------------------------------------------------------------------------
# Conjur was removed from docker-compose.yml (ADR 0036). `docker compose up`
# does not stop containers of services that are no longer in the file, so a
# stack started before that change would keep Conjur running. Remove exactly
# those containers by their compose labels. NOT `--remove-orphans`: that
# would also remove containers from the overlay files (ha, oidc, dynamic-db)
# when this base file runs alone. The conjur-db volume is left in place
# (data is never deleted silently); the command to drop it is printed.
project="$(docker compose config --format json 2>/dev/null | python3 -I -c 'import json,sys; print(json.load(sys.stdin).get("name",""))' 2>/dev/null || true)"
project="${project:-contoso-pam}"
for svc in conjur conjur-cli conjur-db; do
  ids="$(docker ps -aq --filter "label=com.docker.compose.project=$project" --filter "label=com.docker.compose.service=$svc")"
  if [[ -n "$ids" ]]; then
    log "Retiring the old $svc container (Conjur left the lab, ADR 0036)"
    # shellcheck disable=SC2086  # one id per word, on purpose
    docker rm -f $ids >/dev/null
  fi
done
if docker volume inspect "${project}_conjur-db" >/dev/null 2>&1; then
  log "Kept volume ${project}_conjur-db (old Conjur data). Remove it with: docker volume rm ${project}_conjur-db"
fi
log "Starting containers"
docker compose up -d

# 4. Vault ------------------------------------------------------------------------
vault_wait
if [[ "$(vault_cli status -format=json 2>/dev/null | jq -r '.initialized' || true)" != "true" ]]; then
  # ONE key share is a lab shortcut. Production: Shamir 3-of-5 held by
  # different custodians, or auto-unseal via `seal "azurekeyvault"` - the
  # equivalent of protecting a vault's master key.
  log "Initialising Vault (lab: 1 key share)"
  # Write to a temp file and only keep it if it is valid JSON with a root
  # token - an empty/partial init file would break every later script.
  tmp=$(mktemp .secrets/vault-init.XXXXXX)
  vault_cli operator init -key-shares=1 -key-threshold=1 -format=json > "$tmp" \
    || { rm -f "$tmp"; die "vault operator init failed (docker compose logs vault)"; }
  jq -e '.root_token and (.unseal_keys_b64|length>0)' "$tmp" >/dev/null \
    || { rm -f "$tmp"; die "vault operator init returned no keys"; }
  chmod 600 "$tmp" && mv "$tmp" .secrets/vault-init.json
fi
vault_unseal
export VAULT_TOKEN; VAULT_TOKEN="$(root_token)"
if ! vault_cli audit list -format=json 2>/dev/null | jq -e 'has("file/")' >/dev/null; then
  log "Enabling Vault file audit device (every check-out / rotation is logged)"
  vault_cli audit enable file file_path=/vault/logs/audit.log >/dev/null
fi

# 5. Guacamole admin password ----------------------------------------------------
for _ in $(seq 1 60); do curl -fsS "$GUAC_URL/" >/dev/null 2>&1 && break; sleep 3; done
# The web app answers before guac-db has finished loading the schema on a
# first start. Postgres listens on TCP only once its init scripts are done, so
# wait for that instead of retrying logins: the ban extension blocks this
# address for 5 minutes after 5 failed ones.
for _ in $(seq 1 40); do
  docker compose exec -T guac-db pg_isready -q -h 127.0.0.1 >/dev/null 2>&1 && break; sleep 3
done
# Checked on EVERY run: a guac-db reset that keeps .secrets/ (e.g. `docker
# compose down -v`) brings back guacadmin/guacadmin, which would otherwise
# surface only later, as a 403 in psm-session.sh.
tok=""
[[ -f .secrets/guacadmin-password ]] && tok=$(guac_admin_token 2>/dev/null || true)
if [[ -z "$tok" || "$tok" == "null" ]]; then
  tok=$(printf guacadmin | guac_token guacadmin 2>/dev/null || true)
  [[ -n "$tok" && "$tok" != "null" ]] \
    || die "guacadmin login failed with both .secrets/guacadmin-password and the default (docker compose logs guacamole)"
  if [[ -f .secrets/guacadmin-password ]]; then
    log "Stored guacadmin password rejected, default accepted (guac-db was reset) - replacing it again"
  else
    log "Replacing Guacamole's default guacadmin password"
  fi
  # Saved BEFORE the change (0600, then renamed): if the script dies after
  # Guacamole accepted it, the new password is not lost.
  tmp=$(mktemp .secrets/guacadmin-password.XXXXXX)
  printf 'Gx-%s' "$(openssl rand -hex 16)" > "$tmp"
  # Password -> jq on stdin -> curl body on stdin (-d @-): never in any argv.
  jq -Rs '{oldPassword:"guacadmin", newPassword:.}' < "$tmp" \
    | curl -fsS -X PUT -H "Guacamole-Token: $tok" -H 'Content-Type: application/json' \
        "$GUAC_URL/api/session/data/postgresql/users/guacadmin/password" -d @- >/dev/null \
    || { rm -f "$tmp"; die "could not change the guacadmin password"; }
  mv "$tmp" .secrets/guacadmin-password
fi

# Retire the shared t0-operator from earlier versions: every session now runs
# as a named person (psm-session.sh --operator), so a shared login must not
# linger with a password on disk.
tok=$(guac_admin_token)
if [[ "$(curl -sS -o /dev/null -w '%{http_code}' -H "Guacamole-Token: $tok" "$GUAC_URL/api/session/data/postgresql/users/t0-operator")" == 200 ]]; then
  curl -fsS -X DELETE -H "Guacamole-Token: $tok" "$GUAC_URL/api/session/data/postgresql/users/t0-operator" >/dev/null \
    && log "Retired the shared Guacamole user t0-operator (sessions are per person now)"
fi
rm -f .secrets/t0-operator-password
# Same for the shared broker token earlier versions kept on disk: check-outs
# now mint a per-operator token each (psm-session.sh). Revoke, then delete.
if [[ -s .secrets/broker-token ]]; then
  jq -Rs '{token: (. | rtrimstr("\n"))}' < .secrets/broker-token \
    | vault_api POST auth/token/revoke >/dev/null 2>&1 || log "old broker token already invalid"
  rm -f .secrets/broker-token
  log "Retired the shared broker token (check-outs use per-operator tokens now)"
fi

cat <<MSG

PAM / IGA stand-ins are up (loopback only):
  Vault       http://127.0.0.1:8200   root token: jq -r .root_token .secrets/vault-init.json
  Guacamole   $GUAC_URL   guacadmin / \$(cat .secrets/guacadmin-password)  (scripts + History playback only)
              one user per operator (operators.json), created by ./psm-session.sh checkout --operator NAME;
              lab password in .secrets/operators/NAME-password
  ITSM mock   http://127.0.0.1:8084   ServiceNow Table API v2 stand-in (./itsm-ticket.sh add CHG... --operator NAME --approver A --approver B:
              Tier 0 needs two distinct approvers, neither the requester; Tier 1 one)
  midPoint    http://127.0.0.1:8082/midpoint   administrator / \$MIDPOINT_ADMIN_PASSWORD in .env
              (first start: allow a few minutes before it answers)

Next: ./vault-onboard-ad.sh  (needs DC01 built - lab/scripts/dc/README.md)
      then ./discover.sh -> ./onboard.sh -> ./reconcile.sh   (README, "PAM operations pack")
      or test/e2e.sh          (rehearse all of it against a local Samba AD DC, no Azure)
      midpoint/run-campaign.sh  (access-certification campaign; ./pam-up.sh --midpoint starts midPoint alone)
      test/run-all.sh         (every PAM test suite, one total)
MSG
