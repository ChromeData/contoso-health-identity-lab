#!/usr/bin/env bash
# =============================================================================
# splunk-up.sh - start the Splunk second SIEM and prove it is ready for data.
# Idempotent: safe to re-run (after a laptop restart, after editing a .spl).
# -----------------------------------------------------------------------------
# STAND-IN: Splunk Enterprise 60-DAY TRIAL in a local container replaces a
# production Splunk deployment. Data arrives by REPLAY from Log Analytics
# (./ingest-from-loganalytics.sh), standing in for the Splunk Add-on for
# Microsoft Azure / Event Hub streaming. Cost: $0 (trial license, local Docker).
#
#   1. .env with a random admin password + HEC token (mode 0600, gitignored).
#      The LICENSE lines are left EMPTY - accepting Splunk's terms is the
#      human's decision (see step 2).
#   2. License gate: refuses to continue until YOU have set
#        SPLUNK_START_ARGS=--accept-license
#        SPLUNK_GENERAL_TERMS=--accept-sgt-current-at-splunk-com
#      in lab/splunk/.env after reading
#      https://www.splunk.com/en_us/legal/splunk-general-terms.html
#   2b. Header-only, gitignored copies of the two tenant-sensitive lookups
#      (contoso_operator_ips.csv, contoso_sod_holdings.csv) when missing.
#   3. Detections drift check (render-savedsearches.sh --check).
#   4. docker compose up -d, then wait for the image's own healthcheck
#      (first boot under amd64 emulation on Apple Silicon: 5-15 min). Splunk
#      reads the app's .conf files only at start, so a container that was
#      already running is restarted when app/ changed since the last verified
#      run (fingerprint in .state/app.sha256) - otherwise an edited .spl would
#      pass every check below while the OLD search keeps running.
#   5. Pin the HEC token to index=entra (least privilege; REST, idempotent)
#      and read the token back to prove the restriction took.
#   6. Verify: index exists, app loaded, all detections present + scheduled,
#      HEC healthy, one smoke event accepted. Any failure exits non-zero.
#
# HUMAN STEPS: install Docker (Docker Desktop with Rosetta, or Colima with
# --vz-rosetta); read and accept the Splunk General Terms (step 2).
# SECRETS: never printed. The password is read from .env when you need it:
#   grep '^SPLUNK_PASSWORD=' lab/splunk/.env
# =============================================================================
source "$(dirname "$0")/lib.sh"
need docker; need jq; need openssl; need curl

# 1. credentials ---------------------------------------------------------------
if [[ ! -f .env ]]; then
  log "Generating lab/splunk/.env (random admin password + HEC token; license lines left for you)"
  cat > .env <<ENV
# Generated by splunk-up.sh $(date -u +%Y-%m-%dT%H:%M:%SZ). NEVER commit (gitignored).
# Every key is documented in .env.example.
#
# LICENSE - your decision, never a script's. Read
#   ${LICENSE_TERMS_URL}
# and only if you accept, set exactly:
#   SPLUNK_START_ARGS=${LICENSE_START_ARGS}
#   SPLUNK_GENERAL_TERMS=${LICENSE_GENERAL_TERMS}
SPLUNK_START_ARGS=
SPLUNK_GENERAL_TERMS=

# Generated - random per laptop.
SPLUNK_PASSWORD=Sp-$(openssl rand -hex 16)-9a
SPLUNK_HEC_TOKEN=$(new_uuid)

# Optional overrides for ingest-from-loganalytics.sh
LA_RESOURCE_GROUP=rg-identity-lab
LA_WORKSPACE_NAME=loga-idlab
LA_WORKSPACE_ID=
ENV
fi
chmod 600 .env

# Back-fill a generated key if someone emptied it (never touches license lines).
load_env
[[ -n "${SPLUNK_PASSWORD:-}"  ]] || { set_env SPLUNK_PASSWORD "Sp-$(openssl rand -hex 16)-9a"; log "Generated missing SPLUNK_PASSWORD"; }
[[ -n "${SPLUNK_HEC_TOKEN:-}" ]] || { set_env SPLUNK_HEC_TOKEN "$(new_uuid)"; log "Generated missing SPLUNK_HEC_TOKEN"; }
load_env
# Sanity-check the generated values (never printed). HEC tokens must be GUIDs;
# Splunk's default password policy needs >= 8 characters.
re_guid='^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
[[ "$SPLUNK_HEC_TOKEN" =~ $re_guid ]] \
  || die "SPLUNK_HEC_TOKEN in lab/splunk/.env is not a GUID - empty that line and re-run to regenerate it"
(( ${#SPLUNK_PASSWORD} >= 8 )) \
  || die "SPLUNK_PASSWORD in lab/splunk/.env is shorter than 8 characters - before first boot, empty that line and re-run to regenerate it"

# 2. license gate (human) -----------------------------------------------------------
# Same substring test the image's entrypoint applies; we only READ the values.
if [[ "${SPLUNK_START_ARGS:-}" != *"$LICENSE_START_ARGS"* || "${SPLUNK_GENERAL_TERMS:-}" != *"$LICENSE_GENERAL_TERMS"* ]]; then
  cat >&2 <<MSG
ERROR: Splunk license not accepted - this is a human step, so the script stops here.

  1. Read the Splunk General Terms:
       ${LICENSE_TERMS_URL}
  2. Only if you accept them, edit lab/splunk/.env and set exactly:
       SPLUNK_START_ARGS=${LICENSE_START_ARGS}
       SPLUNK_GENERAL_TERMS=${LICENSE_GENERAL_TERMS}
  3. Re-run ./splunk-up.sh

(The 10.x image refuses to start without both; docker compose refuses too.)
MSG
  exit 1
fi

# 2b. tenant-sensitive lookups: header-only, gitignored, never overwritten ---------------
# contoso_operator_ips.csv (the operator's IP, dc-logon detection) and
# contoso_sod_holdings.csv (09-SoD-Report.ps1 -HoldingsSnapshotPath: object
# ids + UPNs). A missing lookup makes inputlookup error on every run instead
# of alerting, so a header-only copy is created when absent; the operator
# fills it by hand. Both paths are in lab/splunk/.gitignore.
ensure_lookup() { # <file> <header>
  local f="app/${SPLUNK_APP}/lookups/$1"
  if [[ ! -f "$f" ]]; then
    ( umask 077; printf '%s\n' "$2" > "$f" )
    log "Created header-only lookup $f (gitignored; fill it by hand)"
  fi
}
ensure_lookup contoso_operator_ips.csv 'IpRange,Owner,ExpiresOn'
ensure_lookup contoso_sod_holdings.csv 'UserObjectId,UserPrincipalName,Kind,Name,SnapshotTime'

# 3. detections as code: the running alerts must equal detections/*.spl ---------------
./render-savedsearches.sh --check

# 4. up + wait for health -------------------------------------------------------------
arch="$(docker info --format '{{.Architecture}}' 2>/dev/null || echo unknown)"
case "$arch" in
  aarch64|arm64) log "Docker host is $arch: splunk/splunk is amd64-only, running under emulation (slow first boot)";;
esac

# Splunk reads the app's .conf files only when splunkd starts. A container
# that was ALREADY running before this run keeps serving the old detections
# after a .spl edit + re-render, and the checks in step 6 would still count
# "5 loaded, 5 scheduled" - a false proof. So: fingerprint the bind-mounted app,
# remember the fingerprint of the last verified run in .state/, and restart a
# pre-existing container when the app changed since then.
mkdir -p .state && chmod 700 .state
APP_FP_FILE=".state/app.sha256"
app_fingerprint() {
  cat "app/${SPLUNK_APP}/default/"*.conf "app/${SPLUNK_APP}/metadata/default.meta" \
    | openssl dgst -sha256 | awk '{print $NF}'
}
app_fp="$(app_fingerprint)"
[[ -n "$app_fp" ]] || die "could not fingerprint app/${SPLUNK_APP}"

pre_cid="$(docker compose ps -q "$SPLUNK_SERVICE" 2>/dev/null || true)"
pre_running="false"
if [[ -n "$pre_cid" ]]; then
  pre_running="$(docker inspect -f '{{.State.Running}}' "$pre_cid" 2>/dev/null || echo false)"
fi

log "Starting Splunk (docker compose up -d)"
docker compose up -d

cid="$(docker compose ps -q "$SPLUNK_SERVICE")"
[[ -n "$cid" ]] || die "compose did not create the $SPLUNK_SERVICE container"

boot_timeout="${SPLUNK_BOOT_TIMEOUT:-1500}"   # seconds; emulated first boot is slow
wait_healthy() {
  local deadline=$((SECONDS + boot_timeout)) last="" state
  while :; do
    state="$(docker inspect -f '{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{else}}nohealth{{end}}' "$cid")"
    case "$state" in
      "running healthy") break ;;
      exited*|dead*)
        docker compose logs --tail 80 "$SPLUNK_SERVICE" >&2 || true
        die "Splunk container stopped ($state) - see the log above" ;;
    esac
    if [[ "$state" != "$last" ]]; then
      # "unhealthy" can be transient while provisioning outlasts the image's
      # start period under emulation; keep waiting until the deadline.
      log "Waiting for Splunk to become healthy (now: $state)"
      last="$state"
    fi
    if (( SECONDS >= deadline )); then
      docker compose logs --tail 80 "$SPLUNK_SERVICE" >&2 || true
      die "Splunk not healthy after ${boot_timeout}s (now: $state). Raise SPLUNK_BOOT_TIMEOUT or check memory (>= 6 GB for the VM)."
    fi
    sleep 10
  done
  log "Container healthy"
}
wait_healthy

# Same container that was already running + app changed since the last
# verified run (or no record of one) -> it is serving stale config.
if [[ "$cid" == "$pre_cid" && "$pre_running" == "true" \
      && "$(cat "$APP_FP_FILE" 2>/dev/null || true)" != "$app_fp" ]]; then
  log "app/${SPLUNK_APP} changed since Splunk last loaded it - restarting the container so the current detections are live"
  docker compose restart "$SPLUNK_SERVICE"
  wait_healthy
fi

info="$(splunk_rest GET '/services/server/info?output_mode=json')" \
  || die "management API on 127.0.0.1:8089 did not accept the admin login"
log "Splunk $(jq -r '.entry[0].content.version // "?"' <<<"$info") up; license: $(jq -r '.entry[0].content.activeLicenseGroup // "?"' <<<"$info")"

# 5. least privilege: this HEC token may write to index=entra only -------------------
# splunk-ansible creates the token named splunk_hec_token from SPLUNK_HEC_TOKEN
# with no index restriction; narrow it. Re-running is a no-op update.
# Splunk's "Use cURL to manage HTTP Event Collector tokens" doc edits a token by
# POSTing index / indexes to data/inputs/http/<name> (only the token's name and
# value cannot change in place). That doc uses the
# servicesNS/<user>/splunk_httpinput namespace; splunk-ansible GETs the same
# token through /services/, which is what this call uses. The read-back below
# PROVES the restriction instead of trusting the POST's 200.
splunk_rest POST "/services/data/inputs/http/${SPLUNK_HEC_TOKEN_NAME}" \
    -d index="$SPLUNK_INDEX" -d indexes="$SPLUNK_INDEX" -d output_mode=json >/dev/null \
  || die "could not pin HEC token '${SPLUNK_HEC_TOKEN_NAME}' to index=${SPLUNK_INDEX}"
tok="$(splunk_rest GET "/services/data/inputs/http/${SPLUNK_HEC_TOKEN_NAME}?output_mode=json")" \
  || die "could not read back HEC token '${SPLUNK_HEC_TOKEN_NAME}'"
# indexes may come back as an array or a comma list; accept either. Only the
# verdict is used - the token value in this response is never printed.
jq -e --arg idx "$SPLUNK_INDEX" '
    .entry[0].content as $c
    | ($c.index == $idx)
      and ([[$c.indexes] | flatten[] | select(. != null) | tostring | split(",")[]
            | gsub("^\\s+|\\s+$"; "") | select(. != "")]
           | length > 0 and all(.[]; . == $idx))' <<<"$tok" >/dev/null \
  || die "HEC token '${SPLUNK_HEC_TOKEN_NAME}' is NOT restricted to index=${SPLUNK_INDEX} after the update (REST read-back of index/indexes)"
unset tok
log "HEC token restricted to index=${SPLUNK_INDEX} (read back)"

# 6. verification -------------------------------------------------------------------------
splunk_rest GET "/services/data/indexes/${SPLUNK_INDEX}?output_mode=json" >/dev/null \
  || die "index '${SPLUNK_INDEX}' missing - is app/${SPLUNK_APP}/default/indexes.conf mounted?"
log "Index ${SPLUNK_INDEX}: present"

splunk_rest GET "/services/apps/local/${SPLUNK_APP}?output_mode=json" >/dev/null \
  || die "app '${SPLUNK_APP}' not loaded - check the bind mount in docker-compose.yml"
log "App ${SPLUNK_APP}: loaded"

expected="$(find detections -maxdepth 1 -type f -name '*.spl' | wc -l | tr -d ' ')"
searches="$(splunk_rest GET "/servicesNS/nobody/${SPLUNK_APP}/saved/searches?output_mode=json&count=0")" \
  || die "could not list saved searches"
found="$(jq --arg app "$SPLUNK_APP" '[.entry[] | select(.acl.app == $app)] | length' <<<"$searches")"
scheduled="$(jq --arg app "$SPLUNK_APP" '[.entry[] | select(.acl.app == $app and (.content.is_scheduled == true or .content.is_scheduled == "1" or .content.is_scheduled == 1))] | length' <<<"$searches")"
jq -r --arg app "$SPLUNK_APP" '.entry[] | select(.acl.app == $app) | "  - \(.name)  [cron \(.content.cron_schedule // "-")]"' <<<"$searches"
[[ "$found" == "$expected" ]] || die "expected $expected detections in app ${SPLUNK_APP}, Splunk loaded $found"
[[ "$scheduled" == "$expected" ]] || die "only $scheduled of $expected detections are scheduled"
log "Detections: $found loaded, $scheduled scheduled"

hec_healthy || die "HEC health endpoint ${SPLUNK_HEC_URL}/services/collector/health is not answering 200"
smoke="$TMP_DIR/smoke.json"
jq -nc --arg idx "$SPLUNK_INDEX" --arg t "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
  '{index: $idx, sourcetype: "contoso:hec:smoketest", source: "splunk-up.sh", host: "splunk-up",
    event: {message: "splunk-up.sh HEC smoke test", at: $t}}' > "$smoke"
hec_post "$smoke" || die "HEC smoke event was rejected (see above)"
log "HEC: healthy, smoke event accepted into index=${SPLUNK_INDEX}"

# Everything verified against THIS app content - remember it (see step 4).
printf '%s\n' "$app_fp" > "$APP_FP_FILE"

cat <<MSG

Splunk second SIEM is up (loopback only):
  Splunk Web   ${SPLUNK_WEB_URL}     admin / SPLUNK_PASSWORD in lab/splunk/.env
  HEC          ${SPLUNK_HEC_URL}    token pinned to index=${SPLUNK_INDEX}
  Alerts       Search & Reporting -> Alerts (filter "Contoso")
  Trial clock  Settings -> Licensing shows the 60-day Enterprise Trial end date.

Next: ./ingest-from-loganalytics.sh --timespan PT24H     (needs 'az login')
      then run detections/*.spl in Search, e.g. failed-signin-spike.spl
MSG
