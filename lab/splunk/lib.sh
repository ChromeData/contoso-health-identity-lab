#!/usr/bin/env bash
# shellcheck disable=SC2034  # constants below are read by the scripts that source this file
# =============================================================================
# lab/splunk/lib.sh - shared helpers for the Splunk second-SIEM scripts.
# Sourced, never executed.
# -----------------------------------------------------------------------------
# STAND-IN: Splunk Enterprise 60-day TRIAL in a local container replaces a
# production Splunk deployment (see README.md and lab/docs/STAND-INS.md).
#
# Secrets (admin password, HEC token) live ONLY in lab/splunk/.env, which
# splunk-up.sh generates at mode 0600 and git ignores. Nothing here ever
# echoes them: REST auth goes through a curl config read from a process
# substitution, and the HEC header through a 0600 temp file, so neither shows
# up in `ps`, in shell history or in terminal output.
#
# Written for the bash 3.2 that ships with macOS: no associative arrays, no
# mapfile, no ${var,,}, and empty arrays are never expanded under `set -u`.
# =============================================================================
set -euo pipefail

SPLUNK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CALLER_PWD="$PWD"     # where the operator ran the script (relative path args)
cd "$SPLUNK_DIR"
umask 077

# Loopback only - docker-compose.yml publishes nothing on other interfaces.
SPLUNK_WEB_URL="http://127.0.0.1:8000"
SPLUNK_MGMT_URL="https://127.0.0.1:8089"
SPLUNK_HEC_URL="https://127.0.0.1:8088"
SPLUNK_INDEX="entra"
SPLUNK_APP="contoso_identity"
SPLUNK_SERVICE="splunk"                     # compose service name
SPLUNK_HEC_TOKEN_NAME="splunk_hec_token"    # name splunk-ansible gives the SPLUNK_HEC_TOKEN input

# The two license-acceptance values the 10.x image checks for (verified
# against the splunk/splunk Docker Hub page and docker-splunk entrypoint.sh,
# 2026-10). Scripts COMPARE against these; they never write them.
LICENSE_START_ARGS="--accept-license"
LICENSE_GENERAL_TERMS="--accept-sgt-current-at-splunk-com"
LICENSE_TERMS_URL="https://www.splunk.com/en_us/legal/splunk-general-terms.html"

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing dependency: $1" >&2; exit 1; }; }
log()  { printf '[%s] %s\n' "$(date -u +%H:%M:%SZ)" "$*"; }
warn() { printf '[%s] WARN: %s\n' "$(date -u +%H:%M:%SZ)" "$*" >&2; }
die()  { echo "ERROR: $*" >&2; exit 1; }

# Per-run scratch directory (0700 via umask), removed on any exit.
TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/contoso-splunk.XXXXXX")"
trap 'rm -rf "$TMP_DIR"' EXIT

load_env() {
  [[ -f .env ]] || die "lab/splunk/.env missing - run ./splunk-up.sh first"
  set -a
  # shellcheck source=/dev/null  # .env is generated by splunk-up.sh and gitignored
  . ./.env
  set +a
}

set_env() { # set_env KEY VALUE  (idempotent edit of .env; values here are hex/uuid only)
  local k="$1" v="$2"
  if grep -q "^${k}=" .env; then
    sed -i.bak "s|^${k}=.*|${k}=${v}|" .env && rm -f .env.bak
  else
    echo "${k}=${v}" >> .env
  fi
}

new_uuid() { # RFC 4122 v4-shaped GUID from openssl (HEC tokens must be GUIDs)
  local h; h="$(openssl rand -hex 16)"
  printf '%s-%s-4%s-%x%s-%s\n' "${h:0:8}" "${h:8:4}" "${h:13:3}" \
    $(( (0x${h:16:1} & 0x3) | 0x8 )) "${h:17:3}" "${h:20:12}"
}

# splunk_rest METHOD PATH [extra curl args...]
#   Calls the management API (8089) as admin. Prints the response body on
#   stdout; returns non-zero (after printing the HTTP status to stderr) on
#   transport failure or any non-2xx status. The password reaches curl through
#   a config file on a pipe, never argv.
splunk_rest() {
  local method="$1" path="$2"; shift 2
  local body="$TMP_DIR/rest-body.$$" code
  code="$(curl -sS -k --max-time 60 -X "$method" \
            -K <(printf 'user = "admin:%s"\n' "${SPLUNK_PASSWORD:?SPLUNK_PASSWORD not loaded}") \
            -o "$body" -w '%{http_code}' "$SPLUNK_MGMT_URL$path" "$@")" || {
    echo "management API unreachable: $method $path" >&2; return 1; }
  cat "$body"; rm -f "$body"
  [[ "$code" == 2* ]] || { echo "HTTP $code from $method $path" >&2; return 1; }
}

# hec_header_file - writes "Authorization: Splunk <token>" to a 0600 temp file
# once and prints its path (curl reads it with -H @file).
hec_header_file() {
  local f="$TMP_DIR/hec-auth.hdr"
  if [[ ! -s "$f" ]]; then
    printf 'Authorization: Splunk %s\n' "${SPLUNK_HEC_TOKEN:?SPLUNK_HEC_TOKEN not loaded}" > "$f"
  fi
  printf '%s\n' "$f"
}

# hec_healthy - HEC's unauthenticated health endpoint answers HTTP 200 when the
# collector is up and accepting events.
hec_healthy() {
  local code
  code="$(curl -sS -k --max-time 10 -o /dev/null -w '%{http_code}' \
            "$SPLUNK_HEC_URL/services/collector/health" 2>/dev/null)" || return 1
  [[ "$code" == "200" ]]
}

# hec_post PAYLOAD_FILE
#   POSTs newline-delimited HEC event envelopes (one JSON object per line) to
#   /services/collector/event. Success = HTTP 200 AND {"code":0}. Retries a
#   busy (503) or unreachable collector twice with back-off; anything else is
#   reported verbatim (Splunk's error JSON carries no secrets) and fails.
hec_post() {
  local payload="$1" resp="$TMP_DIR/hec-resp.json" hdr code attempt
  hdr="$(hec_header_file)"
  for attempt in 1 2 3; do
    code="$(curl -sS -k --max-time 120 -o "$resp" -w '%{http_code}' \
              -H @"$hdr" -H 'Content-Type: application/json' \
              --data-binary @"$payload" "$SPLUNK_HEC_URL/services/collector/event")" || code="000"
    if [[ "$code" == "200" ]] && jq -e '.code == 0' "$resp" >/dev/null 2>&1; then
      return 0
    fi
    if [[ "$code" == "503" || "$code" == "000" ]] && (( attempt < 3 )); then
      warn "HEC answered HTTP $code (attempt $attempt/3) - retrying in $((attempt * 5))s"
      sleep $((attempt * 5))
      continue
    fi
    warn "HEC rejected the batch: HTTP $code $(jq -c . "$resp" 2>/dev/null || head -c 300 "$resp" 2>/dev/null)"
    return 1
  done
  return 1
}
