#!/usr/bin/env bash
# =============================================================================
# render-savedsearches.sh - build the Splunk app's savedsearches.conf from
# detections/*.spl (the single source of truth for the SPL side).
# -----------------------------------------------------------------------------
# STAND-IN context: the alerts it renders run on the Splunk Enterprise 60-day
# TRIAL container (replaces production Splunk) - see README.md.
#
# WHY A RENDERER: each detection lives in ONE readable, paste-able .spl file
# (SPL + its alert schedule), next to its KQL twin in lab/kql. Splunk needs the
# same search inside savedsearches.conf. Hand-copying would drift, so this
# script generates the .conf and splunk-up.sh refuses to start when the
# committed .conf no longer matches the .spl files (--check).
#
# .spl FILE CONTRACT (enforced here, loudly):
#   * Line 1 is the base search (a leading comment breaks a Splunk search).
#   * Commentary is whole-line SPL comments: ``` text ``` - stripped from the
#     .conf. No inline/trailing comments, no multi-line comments, and an even
#     number of double quotes per comment line (paste-safety).
#   * ``` @stanza <saved search name> ```   exactly one per file
#   * ``` @conf <key> = <value> ```          savedsearches.conf settings
#   * SPL lines must not start with "[" or "#" or end with "\" (conf syntax).
#   The search is written as a multi-line conf value (trailing " \"), which
#   is how Splunk itself persists multi-line searches saved from the UI.
#
# USAGE
#   ./render-savedsearches.sh           write app/.../default/savedsearches.conf
#   ./render-savedsearches.sh --check   exit 1 if the committed file is stale
#
# Pure local file work: no network, no Splunk, no secrets. The output is made
# world-readable (0644) because the container's splunk user reads it through
# the bind mount.
# =============================================================================
source "$(dirname "$0")/lib.sh"
need awk; need diff

MODE="write"
case "${1:-}" in
  "")      ;;
  --check) MODE="check" ;;
  -h|--help) awk 'NR > 1 && !/^#/ { exit } NR > 1' "$0"; exit 0 ;;
  *) die "unknown argument: $1 (use --check or nothing)" ;;
esac

OUT="app/${SPLUNK_APP}/default/savedsearches.conf"
TMP_OUT="$TMP_DIR/savedsearches.conf"

shopt -s nullglob
SPL_FILES=(detections/*.spl)
shopt -u nullglob
(( ${#SPL_FILES[@]} > 0 )) || die "no detections/*.spl files found"

render_one() { # render_one FILE -> one savedsearches.conf stanza on stdout
  awk -v src="$1" '
    function fail(msg) { printf "ERROR: %s:%d: %s\n", src, NR, msg > "/dev/stderr"; bad = 1 }
    function strip_comment(s) {
      sub(/^[ \t]*```[ \t]*/, "", s); sub(/[ \t]*```[ \t]*$/, "", s); return s
    }
    # directives
    /^[ \t]*```[ \t]*@stanza[ \t]/ {
      s = strip_comment($0); sub(/^@stanza[ \t]+/, "", s)
      if (stanza != "") fail("second @stanza")
      if (s ~ /[\[\]\/]/) fail("stanza name must not contain [, ] or /")
      stanza = s; next
    }
    /^[ \t]*```[ \t]*@conf[ \t]/ {
      s = strip_comment($0); sub(/^@conf[ \t]+/, "", s)
      if (s !~ /^[A-Za-z0-9_.]+[ \t]*=/) fail("@conf must be: key = value")
      if (s ~ /^search[ \t]*=/) fail("search comes from the SPL lines, not @conf")
      conf[++nc] = s; next
    }
    # whole-line comment: drop it, but keep it paste-safe
    /^[ \t]*```.*```[ \t]*$/ {
      body_txt = $0; q = gsub(/"/, "\"", body_txt)
      if (q % 2 == 1) fail("odd number of double quotes inside a comment line")
      inner = strip_comment($0)
      if (inner ~ /```/) fail("more than one comment on a line")
      next
    }
    /^[ \t]*$/ { next }
    /```/      { fail("inline, trailing or multi-line comment - put comments on their own line"); next }
    {
      line = $0; sub(/[ \t]+$/, "", line)
      if (nb == 0 && NR != 1) fail("the base search must be line 1")
      if (line ~ /^[ \t]*[\[#]/) fail("SPL line may not start with [ or # (conf syntax)")
      if (line ~ /\\$/)          fail("SPL line may not end with a backslash (conf continuation)")
      body[++nb] = line
    }
    END {
      if (stanza == "") fail("missing ``` @stanza <name> ```")
      if (nb == 0)      fail("no SPL lines")
      if (bad) exit 1
      printf "# Source: lab/splunk/%s\n", src
      printf "[%s]\n", stanza
      for (i = 1; i <= nc; i++) print conf[i]
      for (i = 1; i <= nb; i++) {
        if (i == 1) printf "search = %s", body[i]; else printf "%s", body[i]
        if (i < nb) printf " \\\n"; else printf "\n"
      }
      print ""
    }
  ' "$1"
}

{
  cat <<'HDR'
# =============================================================================
# contoso_identity :: savedsearches.conf
# -----------------------------------------------------------------------------
# GENERATED by lab/splunk/render-savedsearches.sh from lab/splunk/detections/*.spl
# DO NOT EDIT BY HAND - edit the .spl file, re-run the renderer, commit both.
# splunk-up.sh runs `render-savedsearches.sh --check` and refuses to start the
# stack if this file is stale.
#
# STAND-IN: these alerts run on the Splunk Enterprise 60-day TRIAL container
# (replaces production Splunk) over Entra logs REPLAYED from Log Analytics
# (replaces the Splunk Add-on for Microsoft Azure / Event Hub streaming).
#
# Each stanza is the SPL twin of one lab/kql rule. Schedules, look-backs,
# severities and grouping mirror the Sentinel rules in
# lab/terraform/modules/monitoring:
#   Sentinel frequency/period -> cron_schedule / dispatch.earliest_time
#   trigger "> 0 rows"         -> counttype = number of events, relation =
#                                 greater than, quantity = 0
#   severity High/Medium/Low   -> alert.severity 5 / 4 / 3
#   incident grouping 1 h by entities -> per-result alerts throttled for 1 h
#                                 on the entity columns (alert.suppress.*)
#   Sentinel suppression       -> alert.suppress.period (legacy-auth: 23 h,
#                                 digest mode, no suppress.fields)
# Alerts land in Activity -> Triggered Alerts (alert.track = 1). No external
# alert action: Teams/ServiceNow response stays on the Sentinel Logic App.
# After the 60-day trial, switching to the Free license stops alerts from
# triggering (scheduled searches still run) - record inside the window.
# =============================================================================

HDR
  for f in "${SPL_FILES[@]}"; do
    render_one "$f" || die "render failed for $f (see errors above)"
  done
} > "$TMP_OUT"

if [[ "$MODE" == "check" ]]; then
  [[ -f "$OUT" ]] || die "$OUT does not exist - run ./render-savedsearches.sh"
  if ! diff -u "$OUT" "$TMP_OUT" >&2; then
    die "$OUT is stale versus detections/*.spl - run ./render-savedsearches.sh and commit the result"
  fi
  log "savedsearches.conf matches detections/*.spl (${#SPL_FILES[@]} detections)"
  exit 0
fi

cp "$TMP_OUT" "$OUT"
chmod 0644 "$OUT"
log "wrote $OUT (${#SPL_FILES[@]} detections)"
