#!/usr/bin/env python3
"""
harness.py - runs every lab/kql detection on a real Kusto engine (the Azure
Data Explorer Kusto emulator, started by run.sh) against synthetic positive
and negative events, and writes a run record.

Python 3.9+ standard library only. Subcommands:

  check                       offline: validate schemas, shims, case files and
                              the itdr-cases.json import; print coverage. No
                              engine, no network.
  render --out DIR            offline: write the exact management commands and
                              queries a run would send (setup.kql, one .kql
                              per case) for review. Not a run record.
  wait --endpoint URL         poll the engine until `.show version` answers.
  guids --record-dir DIR      offline: write DIR/guids.txt, every GUID-shaped
                              value in the record that is not a repeated-digit
                              placeholder and not in the run's inputs (i.e.
                              generated by the engine during the run).
  run --endpoint URL --record-dir DIR [--rules a,b] [--case ID]
                              the run: create the database, tables and shims,
                              run the engine probes, then for every case clear
                              the tables, ingest its rows, run its rule
                              (rendered as modules/monitoring renders it) and
                              assert. Writes results.json, setup.kql and the
                              rendered rules to DIR. Exit 0 only if every rule
                              passed. With --engine-start-failed REASON (run.sh,
                              when the container never answered) it sends
                              nothing and records result ENGINE-START-FAILED,
                              every rule NOT RUN.

Only run.sh starts the engine, and only after the operator passes
--accept-eula (the emulator is licensed under Microsoft's evaluation terms).
Nothing here pulls or starts a container.

The case-file format, the import from itdr-cases.json and every assumption
are documented in README.md next to this file.
"""

