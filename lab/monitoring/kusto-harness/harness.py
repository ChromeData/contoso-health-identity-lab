def run_and_record(args, record_dir, logf):
    started = dt.datetime.now(dt.timezone.utc)
    ctx = load_all()

    def log(msg, stamp=False):
        # Only the start and RESULT lines carry a clock time (as results.json
        # started/finished): per-query or per-phase times would be benchmark
        # data, which the emulator licence (2 d) keeps private.
        line = (f"[{dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}] " if stamp else "") + msg
        print(line, flush=True)
        logf.write(line + "\n")
        logf.flush()

    if ctx["problems"]:
        for p in ctx["problems"]:
            log(f"PROBLEM  {p}")
        log("inputs invalid - nothing sent to the engine")
        return 2
    if not args.accept_eula_recorded:
        log("refusing: run.sh passes --accept-eula-recorded only after the operator accepted the emulator licence")
        return 2

    k = Kusto(args.endpoint)
    run = Runner(ctx, k, log)
    only_rules = set(filter(None, (args.rules or "").split(","))) or None
    selected = [c for c in ctx["cases"]
                if (only_rules is None or c["rule"] in only_rules) and (not args.case or c["id"] == args.case)]
    version, probe_results, results, fatal = {"rows": []}, [], [], None
    if args.engine_start_failed:
        # run.sh: the container exited or never answered. Record that honestly
        # (no query was sent, nothing passed or failed); engine.log is next to
        # this record.
        log("harness.py run: the engine did not start - recording the failure, no query sent", stamp=True)
        fatal = f"engine did not start: {args.engine_start_failed}"
        log("FATAL  " + fatal[:1000])
    else:
        try:
            log(f"harness.py run started; engine {args.endpoint}: .show version", stamp=True)
            version = k.mgmt(".show version", use_db=False)
            log("engine version: " + json.dumps(version["rows"][0] if version["rows"] else {}))
            log(f"setup: database {DB}, {len(ctx['tables'])} tables, {len(ctx['watchlists'])} watchlist store tables, "
                f"shim _GetWatchlist")
            with open(os.path.join(record_dir, "setup.kql"), "w", encoding="utf-8") as f:
                f.write("// The management commands this run sent before the first case (harness.py run).\n\n")
                for scope, c in setup_commands(ctx):
                    f.write(f"// scope: {scope}\n{c}\n\n")
            run.setup()
            probe_results = run_probes(ctx, k, log)
            log(f"cases: {len(selected)}")
            results = run_cases(ctx, run, selected, record_dir, log)
        except KustoError as e:
            fatal = f"engine error outside a case: {e.message}"
            log("FATAL  " + fatal[:1000])

    if only_rules is not None or args.case:
        rule_names = sorted({c["rule"] for c in selected})
    else:
        rule_names = sorted(ctx["rules"])
    per_rule = []
    for name in rule_names:
        rc = [r for r in results if r["rule"] == name]
        pos = sum(1 for r in rc if r["kind"] == "positive")
        neg = sum(1 for r in rc if r["kind"] == "negative")
        ok = pos > 0 and neg > 0 and all(r["status"] in ("PASS", "XFAIL") for r in rc)
        per_rule.append({
            "rule": name, "file": rel(ctx["rules"][name]["path"]), "sha256": ctx["rules"][name]["sha256"],
            # NOT RUN: no case of the rule reached the engine (it did not start,
            # or a fatal error stopped the run first) - never reported as FAIL.
            "result": "PASS" if ok else ("NOT RUN" if not rc else "FAIL"), "positives": pos, "negatives": neg,
            "counts": {s: sum(1 for r in rc if r["status"] == s) for s in ("PASS", "FAIL", "ERROR", "XFAIL", "XPASS")},
            "xfail": sorted({r["xfail"] for r in rc if r["xfail"]}),
        })
    all_pass = bool(per_rule) and fatal is None and all(r["result"] == "PASS" for r in per_rule)
    if args.engine_start_failed:
        overall = "ENGINE-START-FAILED"
    elif only_rules is not None or args.case:
        overall = "PARTIAL-PASS" if all_pass else "PARTIAL-FAIL"
    else:
        overall = "PASS" if all_pass else "FAIL"
    finished = dt.datetime.now(dt.timezone.utc)

    record = {
        "schema": RECORD_SCHEMA,
        "started_utc": started.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "finished_utc": finished.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "tenant": "none: a local Azure Data Explorer Kusto emulator; synthetic events only",
        "result": overall,
        "fatal": fatal,
        "selection": {"rules": sorted(only_rules) if only_rules else "all", "case": args.case or "all"},
        "eula": {"acceptedVia": "run.sh --accept-eula (operator)", "licenseUrl": LICENSE_URL},
        "engine": {"endpoint": "local container (127.0.0.1)", "database": DB,
                   "showVersion": version["rows"][0] if version["rows"] else {},
                   "clearMethod": run.clear_method},
        "environment": tool_versions(args.container, args.image),
        "notRecorded": "per-query timings: the emulator licence (section 2 d) forbids disclosing benchmark "
                       "test results without Microsoft's approval",
        "inputs": {
            "rules": {r["name"]: r["sha256"] for r in ctx["rules"].values()},
            "files": {rel(p): sha256_file(p) for p in sorted(
                [SCHEMAS, SHIMS, os.path.abspath(__file__), os.path.join(HERE, "run.sh")]
                + glob.glob(os.path.join(CASES_DIR, "*.json"))) if os.path.exists(p)},
            "itdrImport": ctx["itdr"],
        },
        "tables": {t: {"columns": {c: s["learn"][c] for c in s["used"]}, "source": s["source"],
                       "readBy": s["readBy"]} for t, s in ctx["tables"].items()},
        "shims": [{"name": n, "variant": v, "sha256": d["sha256"], "purpose": d["purpose"]}
                  for n, vs in ctx["shims"].items() for v, d in vs.items()],
        "probes": probe_results,
        "rules": per_rule,
        "cases": results,
        "skippedImports": ctx["skipped"],
        "summary": {
            "rules": len(per_rule), "rulesPassed": sum(1 for r in per_rule if r["result"] == "PASS"),
            "rulesNotRun": sum(1 for r in per_rule if r["result"] == "NOT RUN"),
            "cases": len(results),
            **{s: sum(1 for r in results if r["status"] == s) for s in ("PASS", "FAIL", "ERROR", "XFAIL", "XPASS")},
            "skippedImports": len(ctx["skipped"]),
        },
    }
    with open(os.path.join(record_dir, "results.json"), "w", encoding="utf-8") as f:
        json.dump(record, f, indent=2, ensure_ascii=False)
        f.write("\n")
    s = record["summary"]
    log(f"RESULT {overall}: rules {s['rulesPassed']}/{s['rules']} passed, {s['rulesNotRun']} not run; "
        f"cases PASS {s['PASS']} FAIL {s['FAIL']} "
        f"ERROR {s['ERROR']} XFAIL {s['XFAIL']} XPASS {s['XPASS']}; imports skipped {s['skippedImports']}", stamp=True)
    return 0 if overall in ("PASS", "PARTIAL-PASS") else 1


def run_probes(ctx, k, log):
    """Engine-semantics probes: what the engine really does where the rules
    (and KqlLite) rely on behaviour Learn does not spell out. Recorded, not
    asserted - the rule cases are the assertions."""
    out = []
    for p in ctx["probes"]:
        entry = {"id": p["id"], "question": p.get("question", ""), "query": p["query"],
                 "reliedOnBy": p.get("reliedOnBy", [])}
        try:
            res = k.query(p["query"])
            entry["columns"] = [c for c, _ in res["columns"]]
            entry["rowCount"] = len(res["rows"])
            entry["rows"] = res["rows"][:5]
        except KustoError as e:
            entry["error"] = e.message
        out.append(entry)
        log(f"probe {p['id']}: " + (f"error: {entry['error'][:200]}" if "error" in entry
                                     else f"{entry['rowCount']} row(s) {json.dumps(entry['rows'])[:300]}"))
    return out


def run_cases(ctx, run, selected, record_dir, log):
    rendered, results = set(), []
    for case in selected:
        entry = {"id": case["id"], "rule": case["rule"], "kind": case["kind"], "label": case["label"],
                 "source": case["source"], "origin": case["origin"], "xfail": case["xfail"],
                 "lets": case["lets"], "tableVariant": case["tableVariant"], "shimVariant": case["shimVariant"]}
        try:
            res, notes, query = run.run_case(case)
            key = f"{case['rule']}__{sha256_text(query)[:12]}.kql"
            if key not in rendered:
                with open(os.path.join(record_dir, "rendered", key), "w", encoding="utf-8") as f:
                    f.write(query)
                rendered.add(key)
            failures, unasserted = evaluate(case, res)
            entry.update({"renderedQuery": "rendered/" + key, "rowCount": len(res["rows"]),
                          "outputColumns": [c for c, _ in res["columns"]], "rows": res["rows"][:5],
                          "failures": failures, "unassertedExpectColumns": unasserted, "notes": notes})
            entry["status"] = status_of(case, bool(failures))
        except KustoError as e:
            entry.update({"error": e.message, "failures": [f"engine error: {e.message[:500]}"]})
            entry["status"] = status_of(case, True) if case["xfail"] else "ERROR"
        except HarnessError as e:
            entry.update({"error": str(e), "failures": [f"harness error: {e}"]})
            entry["status"] = "ERROR"
        results.append(entry)
        first = entry.get("failures") or []
        log(f"{entry['status']:5}  {case['id']}" + (f"  -- {first[0][:300]}" if first else ""))
    return results


