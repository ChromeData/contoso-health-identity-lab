def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def rel(path):
    return os.path.relpath(path, REPO)


def load_json(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError) as e:
        raise HarnessError(f"{rel(path)}: {e}") from e


def kql_code(text):
    """Rule text with // comments removed and string literals blanked, so a
    token scan sees only names the query really uses."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == "@" and i + 1 < n and text[i + 1] in "\"'":
            j = text.find(text[i + 1], i + 2)
            if j < 0:
                raise HarnessError("unterminated verbatim string")
            out.append(" ")
            i = j + 1
            continue
        if c in "\"'":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            out.append(" ")
            i = j + 1
            continue
        if text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def load_rules():
    rules = {}
    for path in sorted(glob.glob(os.path.join(KQL_DIR, "*.kql"))):
        name = os.path.basename(path)[:-4]
        with open(path, encoding="utf-8") as f:
            text = f.read()
        rules[name] = {
            "name": name, "path": path, "text": text, "sha256": sha256_file(path),
            "placeholders": dict(PLACEHOLDER.findall(text)),
            "idents": set(re.findall(r"\b[_A-Za-z][A-Za-z0-9_]*\b", kql_code(text))),
        }
    if not rules:
        raise HarnessError(f"no rules in {rel(KQL_DIR)}")
    return rules


def load_schemas(rules):
    raw = load_json(SCHEMAS)
    tables = {}
    for tname, spec in raw["tables"].items():
        learn = spec["learnColumns"]
        used = {c for r in rules.values() if tname in r["idents"] for c in learn if c in r["idents"]}
        if "TimeGenerated" in learn:
            used.add("TimeGenerated")
        # TimeGenerated first, the rest alphabetical: the .append projection
        # follows this order (ingest-from-query matches columns by position).
        used = sorted(used, key=lambda s: (s != "TimeGenerated", s.lower()))
        for c in used:
            if not IDENT.match(c) or learn[c] not in CONVERT:
                raise HarnessError(f"schemas.json {tname}.{c}: unsupported name or type {learn[c]!r}")
        variants = spec.get("variants") or {"default": {"drop": []}}
        default_variant = spec.get("defaultVariant", next(iter(variants)))
        tables[tname] = {
            "name": tname, "learn": learn, "used": used, "source": spec["source"],
            "variants": {v: [c for c in used if c not in set(d.get("drop", []))] for v, d in variants.items()},
            "defaultVariant": default_variant,
            "readBy": sorted(r["name"] for r in rules.values() if tname in r["idents"]),
        }
    watchlists = {}
    for alias, spec in raw["watchlists"].items():
        if alias.startswith("_"):
            continue
        for c, t in spec["columns"].items():
            if not IDENT.match(c) or t not in CONVERT:
                raise HarnessError(f"schemas.json watchlist {alias}.{c}: unsupported name or type")
        watchlists[alias] = {"alias": alias, "table": spec["table"], "columns": spec["columns"], "source": spec["source"]}
    return tables, watchlists


def load_shims():
    with open(SHIMS, encoding="utf-8") as f:
        text = f.read()
    shims = {}
    blocks = re.split(r"(?m)^//@shim\s+", text)[1:]
    for b in blocks:
        head, _, body = b.partition("\n")
        attrs = dict(kv.split("=", 1) for kv in head.split())
        lines = [ln for ln in body.splitlines() if not ln.lstrip().startswith("//")]
        cmd = "\n".join(lines).strip()
        if not cmd.startswith("."):
            raise HarnessError(f"shims.kql {head}: block has no management command")
        purpose = " ".join(ln.strip()[2:].strip() for ln in body.splitlines() if ln.lstrip().startswith("//"))
        shims.setdefault(attrs["name"], {})[attrs["variant"]] = {
            "command": cmd, "sha256": sha256_text(cmd), "purpose": purpose}
    if "default" not in shims.get("_GetWatchlist", {}):
        raise HarnessError("shims.kql: _GetWatchlist default variant missing")
    return shims


# ------------------------------------------------------------------ cases ----

def expand_rows(rows, defaults):
    out = []
    for row in rows:
        if not isinstance(row, dict):
            raise HarnessError(f"row is not an object: {row!r}")
        n = int(row.get("_repeat", 1))
        body = {k: v for k, v in row.items() if k != "_repeat"}
        for i in range(n):
            r = copy.deepcopy(defaults)
            for k, v in body.items():
                r[k] = v.replace("{i}", str(i)) if isinstance(v, str) else copy.deepcopy(v)
            out.append(r)
    return out


def load_hand_cases(rules):
    cases, problems = [], []
    for path in sorted(glob.glob(os.path.join(CASES_DIR, "*.json"))):
        if os.path.basename(path).startswith("_"):
            continue
        doc = load_json(path)
        rule = doc.get("rule")
        if rule not in rules:
            problems.append(f"{rel(path)}: rule {rule!r} is not a lab/kql rule")
            continue
        defaults = doc.get("defaults", {})
        seen = set()
        for c in doc.get("cases", []):
            cid = c.get("id")
            if not cid or cid in seen:
                problems.append(f"{rel(path)}: missing or duplicate case id {cid!r}")
                continue
            seen.add(cid)
            tables = {t: expand_rows(rows, defaults.get(t, {})) for t, rows in c.get("tables", {}).items()}
            cases.append({
                "rule": rule, "id": f"{rule}/{cid}", "label": c.get("label", ""), "kind": c.get("kind"),
                "source": rel(path), "origin": "hand", "tables": tables,
                "defaultsKeys": {t: set(defaults.get(t, {})) for t in tables},
                "watchlists": c.get("watchlists", {}), "lets": c.get("lets", {}),
                "tableVariant": c.get("tableVariant", {}), "shimVariant": c.get("shimVariant", {}),
                "expect": c.get("expect", []), "expectNone": c.get("expectNone", []),
                "expectRows": c.get("expectRows"), "xfail": c.get("xfail"),
            })
    return cases, problems


def merge_map(a, b):
    out = dict(a or {})
    out.update(b or {})
    return out


def load_itdr_import(rules):
    """Rows of lab/scripts/monitoring/tests/fixtures/itdr-cases.json (read
    only) that are whole raw table rows become engine cases; stage-level rows
    are skipped with the reason."""
    if not os.path.exists(ITDR_CASES):
        return [], [{"source": rel(ITDR_CASES), "reason": "file not found - import skipped"}], None
    doc = load_json(ITDR_CASES)
    overrides = load_json(OVERRIDES).get("overrides", []) if os.path.exists(OVERRIDES) else []
    used_overrides = set()
    cases, skipped = [], []
    for c in doc:
        rule, table = c.get("rule"), c.get("table")
        for r in c.get("rows") or []:
            label = r.get("label", "")
            where = {"rule": rule, "label": label}
            if rule not in rules:
                skipped.append({**where, "reason": "rule not in lab/kql"})
                continue
            if c.get("query"):
                skipped.append({**where, "reason": "case runs a let's pipeline only (query), not the rule"})
                continue
            if r.get("afterSummarize"):
                skipped.append({**where, "reason": "stage-level (aggregated) rows, not table rows; "
                                                  f"raw-event equivalents are in cases/{rule}.json"})
                continue
            joins = merge_map(c.get("joinRows"), r.get("joinRows"))
            if any((spec or {}).get("rows") for spec in joins.values()):
                skipped.append({**where, "reason": "row-level joinRows (derived let rows); "
                                                  f"raw-event equivalents are in cases/{rule}.json"})
                continue
            lets = merge_map(c.get("lets"), r.get("lets"))
            bad = [k for k in lets if k not in rules[rule]["placeholders"]]
            if bad:
                skipped.append({**where, "reason": f"overrides non-rendered lets {bad}; raw-event equivalents are in cases/{rule}.json"})
                continue
            if "row" not in r:
                skipped.append({**where, "reason": "no row"})
                continue
            kind = "positive" if r.get("expect") is not None else "negative"
            slug = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")[:70]
            case = {
                "rule": rule, "id": f"{rule}/itdr:{slug}", "label": label, "kind": kind,
                "source": rel(ITDR_CASES) + f" [{c.get('case', '')}]", "origin": "itdr-import",
                "tables": {table: [copy.deepcopy(r["row"])]}, "defaultsKeys": {table: set()},
                "watchlists": {}, "lets": lets, "tableVariant": {}, "shimVariant": {},
                "expect": [r["expect"]] if kind == "positive" else [], "expectNone": [],
                "expectRows": None, "xfail": None,
            }
            for o in overrides:
                if o.get("rule") == rule and o.get("label") == label:
                    used_overrides.add((rule, label))
                    if o.get("xfail"):
                        case["xfail"] = o["xfail"]
            cases.append(case)
    stale = [o for o in overrides if (o.get("rule"), o.get("label")) not in used_overrides]
    return cases, skipped, {"sha256": sha256_file(ITDR_CASES), "path": rel(ITDR_CASES), "staleOverrides": stale}


def validate_cases(cases, rules, tables, watchlists, shims):
    problems = []
    for k in cases:
        cid = k["id"]
        if k["kind"] not in ("positive", "negative"):
            problems.append(f"{cid}: kind must be positive or negative")
        if k["kind"] == "positive" and not k["expect"]:
            problems.append(f"{cid}: a positive case needs expect")
        if k["kind"] == "negative" and k["expect"]:
            problems.append(f"{cid}: a negative case cannot have expect (use expectNone)")
        if k["xfail"] and not XFAIL.match(k["xfail"]):
            problems.append(f"{cid}: xfail must read 'CODE-NEEDED-<n>: <reason>'")
        for name in k["lets"]:
            if name not in rules[k["rule"]]["placeholders"]:
                problems.append(f"{cid}: lets.{name} is not a Terraform-rendered placeholder let of {k['rule']}")
            # Strings (object ids, CIDRs, ASNs) or whole numbers (the PIM
            # working hours / days lists); never booleans or mixed types.
            elif not (isinstance(k["lets"][name], list) and (
                    all(isinstance(x, str) for x in k["lets"][name]) or
                    all(isinstance(x, int) and not isinstance(x, bool) for x in k["lets"][name]))):
                problems.append(f"{cid}: lets.{name} must be a list of strings (object ids, ranges) or of whole numbers")
        for t, variant in k["tableVariant"].items():
            if t not in tables or variant not in tables[t]["variants"]:
                problems.append(f"{cid}: unknown table variant {t}={variant}")
        for name, variant in k["shimVariant"].items():
            if variant not in shims.get(name, {}):
                problems.append(f"{cid}: unknown shim variant {name}={variant}")
        for t, rows in k["tables"].items():
            if t not in tables:
                problems.append(f"{cid}: unknown table {t}")
                continue
            if k["rule"] not in tables[t]["readBy"]:
                problems.append(f"{cid}: {k['rule']} does not read {t}")
            variant_cols = set(tables[t]["variants"][k["tableVariant"].get(t, tables[t]["defaultVariant"])])
            for row in rows:
                for col in row:
                    if col not in tables[t]["learn"]:
                        problems.append(f"{cid}: {t} has no column {col!r} (schemas.json learnColumns, from Learn)")
                    elif col in tables[t]["used"] and col not in variant_cols and col not in k["defaultsKeys"].get(t, set()):
                        problems.append(f"{cid}: {t} variant has no column {col!r}")
        for alias, items in k["watchlists"].items():
            if alias not in watchlists:
                problems.append(f"{cid}: unknown watchlist {alias}")
                continue
            for item in items:
                for col in item:
                    if col not in watchlists[alias]["columns"]:
                        problems.append(f"{cid}: watchlist {alias} has no column {col!r}")
        for group in ("expect", "expectNone"):
            if not isinstance(k[group], list) or not all(isinstance(e, dict) and e for e in k[group]):
                problems.append(f"{cid}: {group} must be a list of non-empty objects")
    return problems


def coverage(cases, rules):
    cov = {r: {"positive": 0, "negative": 0, "hand": 0, "itdr-import": 0} for r in rules}
    for k in cases:
        cov[k["rule"]][k["kind"]] = cov[k["rule"]].get(k["kind"], 0) + 1
        cov[k["rule"]][k["origin"]] += 1
    return cov


def load_all():
    rules = load_rules()
    tables, watchlists = load_schemas(rules)
    shims = load_shims()
    hand, problems = load_hand_cases(rules)
    imported, skipped, itdr_meta = load_itdr_import(rules)
    cases = hand + imported
    problems += validate_cases(cases, rules, tables, watchlists, shims)
    probes = load_json(PROBES).get("probes", [])
    return {"rules": rules, "tables": tables, "watchlists": watchlists, "shims": shims, "cases": cases,
            "skipped": skipped, "itdr": itdr_meta, "probes": probes, "problems": problems}


# ---------------------------------------------------------------- render ----

def render_rule(rule, lets):
    text = rule["text"]
    for name, values in sorted(lets.items()):
        ph = rule["placeholders"][name]
        old = f"dynamic([]); // @@{ph}@@"
        new = f"dynamic({json.dumps(values, separators=(',', ':'))}); // @@{ph}@@"
        if text.count(old) != 1:
            raise HarnessError(f"{rule['name']}: placeholder @@{ph}@@ found {text.count(old)} times")
        text = text.replace(old, new)
    return text


def table_ddl(name, cols, types):
    return f".create table {name} (" + ", ".join(f"{c}:{types[c]}" for c in cols) + ")"


def setup_commands(ctx):
    cmds = [("cluster", f'.create database {DB} persist (@"/kustodata/dbs/{DB}/md", @"/kustodata/dbs/{DB}/data")')]
    for t in ctx["tables"].values():
        cols = t["variants"][t["defaultVariant"]]
        cmds.append(("db", table_ddl(t["name"], cols, t["learn"])))
    for w in ctx["watchlists"].values():
        cmds.append(("db", table_ddl(w["table"], list(w["columns"]), w["columns"])))
    cmds.append(("db", ctx["shims"]["_GetWatchlist"]["default"]["command"]))
    return cmds


def resolve_value(v, col_type, base):
    if isinstance(v, str):
        m = REL_TIME.match(v)
        if m and col_type in ("datetime", "string"):
            unit = {"s": "seconds", "m": "minutes", "h": "hours", "d": "days"}[m.group(3)]
            delta = dt.timedelta(**{unit: int(m.group(2))})
            when = base - delta if m.group(1) == "ago" else base + delta
            return when.strftime("%Y-%m-%dT%H:%M:%S.%fZ")
    if col_type == "string" and isinstance(v, (dict, list)):
        return json.dumps(v, separators=(",", ":"))
    return v


def prepare_rows(rows, cols, types, base, defaults_keys, learn):
    out, dropped = [], set()
    for row in rows:
        r = dict(row)
        if "TimeGenerated" in types and "TimeGenerated" not in r:
            r["TimeGenerated"] = DEFAULT_TIME
        clean = {}
        for k, v in r.items():
            if k not in cols:
                if k in learn or k in defaults_keys:
                    dropped.add(k)
                    continue
                raise HarnessError(f"column {k!r} is not in the table")
            clean[k] = resolve_value(v, types[k], base)
        out.append(clean)
    return out, sorted(dropped)


def append_command(table, cols, types, rows):
    payload = json.dumps(rows, ensure_ascii=True, separators=(",", ":")).replace("'", "''")
    proj = []
    for c in cols:
        fn = CONVERT[types[c]]
        proj.append(f"{c} = {fn}(harness_r['{c}'])" if fn else f"{c} = harness_r['{c}']")
    return (f".append {table} <|\n"
            f"print harness_rows = parse_json(@'{payload}')\n"
            f"| mv-expand harness_r = harness_rows\n"
            f"| project " + ",\n    ".join(proj))


def case_commands(ctx, k, base):
    """The .append commands for one case (rows resolved against base)."""
    cmds, notes = [], []
    for t, rows in sorted(k["tables"].items()):
        spec = ctx["tables"][t]
        variant = k["tableVariant"].get(t, spec["defaultVariant"])
        cols = spec["variants"][variant]
        prepared, dropped = prepare_rows(rows, cols, spec["learn"], base, k["defaultsKeys"].get(t, set()), spec["learn"])
        if dropped:
            notes.append(f"{t}: fixture columns not in the harness table, ignored: {', '.join(dropped)}")
        if prepared:
            cmds.append((t, append_command(t, cols, spec["learn"], prepared)))
    for alias, items in sorted(k["watchlists"].items()):
        w = ctx["watchlists"][alias]
        prepared, _ = prepare_rows(items, list(w["columns"]), w["columns"], base, set(), {})
        if prepared:
            cmds.append((w["table"], append_command(w["table"], list(w["columns"]), w["columns"], prepared)))
    return cmds, notes


def cmd_render(args):
    ctx = load_all()
    if ctx["problems"]:
        for p in ctx["problems"]:
            print(f"PROBLEM  {p}")
        return 1
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    base = dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc)
    banner = ("// RENDER ONLY - generated by harness.py render for review. Not a run record:\n"
              "// no engine ran. Relative times are resolved against 2026-01-01T00:00:00Z here;\n"
              "// a run resolves them against the engine's now() before each case.\n\n")
    with open(os.path.join(out, "setup.kql"), "w", encoding="utf-8") as f:
        f.write(banner)
        for scope, c in setup_commands(ctx):
            f.write(f"// scope: {scope}\n{c}\n\n")
    n = 0
    for k in ctx["cases"]:
        d = os.path.join(out, k["rule"])
        os.makedirs(d, exist_ok=True)
        cmds, notes = case_commands(ctx, k, base)
        fname = re.sub(r"[^A-Za-z0-9_.-]+", "_", k["id"].split("/", 1)[1]) + ".kql"
        with open(os.path.join(d, fname), "w", encoding="utf-8") as f:
            f.write(banner)
            f.write(f"// case {k['id']} ({k['kind']}) - {k['label']}\n// source: {k['source']}\n")
            for nline in notes:
                f.write(f"// note: {nline}\n")
            for t, c in cmds:
                f.write(f"\n// ingest {t}\n{c}\n")
            f.write("\n// query\n" + render_rule(ctx["rules"][k["rule"]], k["lets"]) + "\n")
        n += 1
    print(f"rendered setup.kql and {n} case files to {out}")
    return 0


