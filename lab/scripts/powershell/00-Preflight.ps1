    verify: the trial's part number, and any step-up SKU name.

.PARAMETER BudgetCapUsd
    The lab's spending cap in USD (expected spend is about $45-60). Default 150.

.PARAMETER RepoRoot
    Repository root. Default: three levels above this script.

.EXAMPLE
    ./00-Preflight.ps1 -Offline
    Tools, versions and repo state; no tenant needed.

.EXAMPLE
