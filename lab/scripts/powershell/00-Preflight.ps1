<#
.SYNOPSIS
    Tenant-day preflight: "am I ready to start a trial day?" Read-only. Prints
    PASS / WARN / FAIL lines and exits 0 (ready), 1 (ready, read the warnings)
    or 2 (blocked: fix every FAIL first; also when the script itself stops on
    an unexpected error).

.DESCRIPTION
    Run it before the day's first flag-flip PR or post-apply step. It
    changes nothing: no sign-in, no writes (git runs with
    --no-optional-locks, so not even the index is refreshed), so there is no
    -WhatIf. It never prints a tenant, subscription or object id, a token, a
    secret, a UPN or a home-folder path (every detail line is redacted on the
    way out, error texts included); the tenant shows as its domain.

    -Offline   local tools, versions and repo state only. Runs no az command
               (any az command may send telemetry) and never touches
               Microsoft Graph. Terraform runs with CHECKPOINT_DISABLE=1 and
               trufflehog with --no-update (no release checks).
    (default)  everything -Offline checks, plus read-only checks of the
               current az CLI session and Microsoft Graph connection.

    [1] PowerShell and modules
        pwsh 7.x (the lab scripts #Requires 7.0; this script does not, so it
        can tell Windows PowerShell 5.1 apart); every Microsoft Graph
        sub-module the lab installs, at the CI pin (.github/workflows/
        lab-tests.yml, 2.41.2: mocks copy cmdlet signatures from it, and
        every sub-module must match Microsoft.Graph.Authentication, so a
        stray newer version of one sub-module is a WARN too); Pester 5.5+
        (tests/Invoke-LabTests.ps1) and PSScriptAnalyzer.
    [2] Command-line tools
        terraform against every envs/* required_version and the CI pin (the
        committed .terraform.lock.hcl files were generated by it); az on
        PATH (online mode also reads `az version`); gitleaks and trufflehog
        (the pre-push gate, so missing = FAIL); shellcheck, actionlint and
        gh (version only: `gh auth status` calls GitHub, run it yourself).
    [3] Containers
        docker + Colima and a reachable daemon, for the PAM / IGA stand-ins.
    [4] Repository
        git branch, uncommitted changes, upstream (as of the last fetch: this
        script never fetches), a remote to open PRs on, and that this is the
        published clone, not the build source it is made from (only the build
        source carries the release script); lab/terraform/envs/dev/lab.tfvars: every staging flag
        false and every ca_policy_states entry report-only, unless named in
        -ExpectedOnFlags / -ExpectedEnforcedPolicies (flags flipped on purpose
        on an earlier trial day).
    [5] Azure CLI session (online)
        signed in, the tenant's domain, a selected subscription, a user (not a
        service principal); CA010-safe login (WARN if the last `az login` in
        az's own command log used --use-device-code); Azure cost budget vs
        the $150 cap, with the trial auto-renew reminder.
    [6] Microsoft Graph (online)
        a delegated, non-device-code connection to the same tenant as az;
        every delegated scope the post-apply scripts and 01-Verify-Baseline.ps1
        declare (read from their `$requiredScopes` lines, so it cannot drift)
        plus Organization.Read.All for this script; the tenant's initial
        domain (-OnMicrosoftDomain must match; without it the tenant is not
        compared, a WARN: the lab also holds a B2B partner tenant); licensed
        SKUs (subscribedSkus):
        Microsoft 365 E5 and Microsoft Entra ID Governance enabled and
        assigned, the AAD_PREMIUM_P2 service plan, Teams when E5 is the
        "(no Teams)" SKU; both break-glass accounts (mailNickname bg-admin-*,
        the modules/groups convention) enabled, on *.onmicrosoft.com, licensed.
        Their CA exclusion and Global Administrator role are
        01-Verify-Baseline.ps1's job, not this script's.

    A source that cannot be read is reported as such (FAIL or WARN), never as
    "nothing there".

.PARAMETER Offline
    Local checks only: no az, no Microsoft Graph, no tenant.

.PARAMETER OnMicrosoftDomain
    The lab tenant's initial domain (<tenant>.onmicrosoft.com). When given, a
    Graph (or az) session on any other tenant is a FAIL; online without it,
    the Graph tenant line is a WARN (not compared).

.PARAMETER ExpectedOnFlags
    lab.tfvars staging flags already flipped on purpose (an earlier trial day's
    PR). Any other flag that is true is a FAIL: it would start a clock or
    deploy before its day.

.PARAMETER ExpectedEnforcedPolicies
    CA policy ids (CA001...) already graduated to "enabled" on purpose. Any
    other "enabled" policy is a FAIL.

.PARAMETER PreTrial
    Phase 1 / Day 0, before the E5 and Governance trials are started: missing
    SKUs and unlicensed break-glass accounts are WARN instead of FAIL.

.PARAMETER E5SkuPartNumbers
    skuPartNumber values that count as Microsoft 365 E5. Learn "Product names
