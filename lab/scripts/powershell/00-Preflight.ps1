function ConvertFrom-GitStatus {
    # First line of `git status --porcelain=v1 --branch`, plus the number of
    # changed paths. Upstream numbers are as of the last fetch.
    param([AllowNull()][AllowEmptyString()][string]$Text)
    $lines = @([string]$Text -split "\r?\n" | Where-Object { $_ })
    $r = [ordered]@{ Branch = ''; Upstream = ''; Ahead = 0; Behind = 0; Gone = $false; Detached = $false; Changes = 0 }
    $head = @($lines | Where-Object { $_.StartsWith('## ') }) | Select-Object -First 1
    $r.Changes = @($lines | Where-Object { -not $_.StartsWith('## ') }).Count
    if ($head) {
        $h = $head.Substring(3)
        $rel = ''
        $i = $h.IndexOf(' [')
        if ($i -ge 0) { $rel = $h.Substring($i + 2).TrimEnd(']'); $h = $h.Substring(0, $i) }
        $h = $h -replace '^(No commits yet on|Initial commit on) ', ''
        $parts = $h -split '\.\.\.', 2
        $r.Branch = $parts[0]
        if ($parts.Count -gt 1) { $r.Upstream = $parts[1] }
        $r.Detached = $r.Branch -like 'HEAD (no branch)*'
        if ($rel -match 'ahead (\d+)') { $r.Ahead = [int]$Matches[1] }
        if ($rel -match 'behind (\d+)') { $r.Behind = [int]$Matches[1] }
        $r.Gone = $rel -eq 'gone'
    }
    return [pscustomobject]$r
}

function ConvertFrom-GitRemote {
    # `git remote -v` -> name + host/path, with any embedded credentials or
    # user removed (https://<cred>@host/x, ssh://git@host/x, git@host:x).
    param([AllowNull()][AllowEmptyString()][string]$Text)
    $seen = [ordered]@{}
    foreach ($l in @([string]$Text -split "\r?\n" | Where-Object { $_ })) {
        $m = [regex]::Match($l, '^(\S+)\s+(\S+)')
        if ($m.Success -and -not $seen.Contains($m.Groups[1].Value)) {
            $u = ($m.Groups[2].Value -replace '(?<=://)[^/@\s]+@', '') -replace '^[a-z+]+://', ''
            $seen[$m.Groups[1].Value] = $u -replace '^[^@/:\s]+@([^/:\s]+):', '$1/'
        }
    }
    return @($seen.Keys | ForEach-Object { [pscustomobject]@{ Name = $_; Url = $seen[$_] } })
}

function Get-GitFinding {
    param([bool]$IsRepo, [AllowNull()]$Status, [AllowEmptyCollection()][object[]]$Remotes = @(), [bool]$IsBuildSource = $false)
    $c = 'git'
    if (-not $IsRepo) { return @(ConvertTo-PreflightFinding $c 'FAIL' 'not a git checkout - every flag flip is a PR from a clone of the public repo') }
    $out = [System.Collections.Generic.List[object]]::new()
    if ($IsBuildSource) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' 'this checkout is the build source, not the published clone (it carries the release script). Trial PRs run from the published clone')) }
    if ($null -eq $Status) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "'git status' could not be read")); return $out.ToArray() }
    if ($Status.Detached) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' 'detached HEAD: check out main (or the PR branch) first')) }
    if ($Status.Changes -gt 0) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "$($Status.Changes) uncommitted change(s) on $($Status.Branch): commit or stash, so a flag-flip PR's plan shows only the change you meant")) }
    $r = @($Remotes | Where-Object { $_ })
    if ($r.Count -eq 0) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' 'no git remote: flag flips are PRs on the public repo - clone it and run from there')) }
    if ($Status.Gone) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "the upstream of $($Status.Branch) is gone")) }
    if ($Status.Behind -gt 0) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "$($Status.Branch) is $($Status.Behind) commit(s) behind $($Status.Upstream) as of the last fetch: git pull")) }
    if ($out.Count -eq 0) {
        $up = if ($Status.Upstream) { "tracking $($Status.Upstream)" } else { 'no upstream yet' }
        if ($Status.Ahead -gt 0) { $up += ", $($Status.Ahead) ahead" }
        $rm = @($r | ForEach-Object { "$($_.Name) -> $($_.Url)" }) -join '; '
        $out.Add((ConvertTo-PreflightFinding $c 'PASS' "branch $($Status.Branch), clean, $up; $rm"))
    }
    return $out.ToArray()
}

function Get-PostApplyScopeSet {
    # Union of the delegated scopes the given scripts declare in their
    # `$requiredScopes = ...` assignments (every branch of a conditional
    # assignment counts), read from their syntax trees.
    param([AllowEmptyCollection()][string[]]$Path = @())
    $set = [System.Collections.Generic.SortedSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
    $read = 0; $broken = [System.Collections.Generic.List[string]]::new()
    foreach ($p in @($Path | Where-Object { $_ })) {
        $tokens = $null; $errors = $null
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($p, [ref]$tokens, [ref]$errors)
        $read++
        # A script that does not parse (mid-edit) may hide its declaration.
        if (@($errors).Count) { $broken.Add([System.IO.Path]::GetFileName($p)) }
        $assigns = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.AssignmentStatementAst] -and $n.Left.Extent.Text -eq '$requiredScopes' }, $true)
        foreach ($a in $assigns) {
            foreach ($s in $a.Right.FindAll({ param($n) $n -is [System.Management.Automation.Language.StringConstantExpressionAst] }, $true)) {
                if ($s.Value -match '^[A-Za-z]+(\.[A-Za-z]+)+$') { [void]$set.Add($s.Value) }
            }
        }
    }
    return [pscustomobject]@{ Scopes = @($set); FilesRead = $read; ParseErrors = $broken.ToArray() }
}

