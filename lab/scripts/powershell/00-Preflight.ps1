}

function Read-LabTfvarsFile {
    # envs/dev/lab.tfvars is flat by design (policy knobs only): every
    # top-level `name = true|false` is a staging flag, and ca_policy_states is
    # the one map. Line-based on purpose - no HCL parser on the operator Mac.
    param([AllowNull()][AllowEmptyString()][string]$Text)
    $flags = [ordered]@{}; $ca = [ordered]@{}; $inCa = $false; $sawCa = $false
    foreach ($raw in @([string]$Text -split "\r?\n")) {
        $line = ($raw -replace '^\s*(#|//).*$', '') -replace '\s+(#|//).*$', ''
        if ($line -match '^\s*$') { continue }
        if ($inCa) {
            if ($line -match '^\s*\}') { $inCa = $false; continue }
            if ($line -match '^\s*"?(CA\d+)"?\s*=\s*"([^"]*)"') { $ca[$Matches[1].ToUpperInvariant()] = $Matches[2] }
            continue
        }
        if ($line -match '^\s*ca_policy_states\s*=\s*\{') { $inCa = $true; $sawCa = $true; continue }
        if ($line -match '^\s*([A-Za-z0-9_]+)\s*=\s*(true|false)\s*$') { $flags[$Matches[1]] = ($Matches[2] -eq 'true') }
    }
    return [pscustomobject]@{ Flags = $flags; CaStates = $ca; HasCaBlock = $sawCa; Unterminated = $inCa }
}

function Get-TfvarsFinding {
    # lab.tfvars: nothing on before its day, every CA policy report-only.
    param(
        [AllowNull()]$Parsed,
        [AllowEmptyCollection()][string[]]$ExpectedOnFlags = @(),
        [AllowEmptyCollection()][string[]]$ExpectedEnforcedPolicies = @(),
        [string]$Path = 'lab/terraform/envs/dev/lab.tfvars'
    )
    $out = [System.Collections.Generic.List[object]]::new()
    if ($null -eq $Parsed) { $out.Add((ConvertTo-PreflightFinding 'lab.tfvars' 'FAIL' "not found at $Path - every flag flip is a PR against it")); return $out.ToArray() }
    # Staging flags.
    $c = 'lab.tfvars staging flags'
    $names = @($Parsed.Flags.Keys)
    $on = @($names | Where-Object { $Parsed.Flags[$_] })
    $unexpected = @($on | Where-Object { $_ -notin $ExpectedOnFlags })
    $acked = @($on | Where-Object { $_ -in $ExpectedOnFlags })
    $stale = @($ExpectedOnFlags | Where-Object { $_ -and $_ -notin $on })
    if ($names.Count -eq 0) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "no 'name = true|false' line parsed from $Path")) }
    elseif ($unexpected.Count) {
        $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "on before its day: $($unexpected -join ', '). Each flag flips in its own PR on its trial day (a flag can start a clock or deploy early); if it was flipped on purpose, name it in -ExpectedOnFlags"))
    }
    else {
        $detail = "$($names.Count) flags, all false"
        if ($acked.Count) { $detail = "$($names.Count) flags; on by design (-ExpectedOnFlags): $($acked -join ', '); the rest false" }
        $out.Add((ConvertTo-PreflightFinding $c 'PASS' $detail))
    }
    if ($stale.Count) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "-ExpectedOnFlags names $($stale -join ', '), but lab.tfvars has it false or missing")) }
    # Conditional Access states.
    $c = 'lab.tfvars ca_policy_states'
    if (-not $Parsed.HasCaBlock) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "no ca_policy_states map in $Path")); return $out.ToArray() }
    if ($Parsed.Unterminated) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "the ca_policy_states map in $Path is not closed")); return $out.ToArray() }
    $states = $Parsed.CaStates
    $ids = @($states.Keys)
    $bad = 0
    foreach ($id in $ids) {
        $s = [string]$states[$id]
        switch -CaseSensitive ($s) {
            'enabledForReportingButNotEnforced' { }
            'enabled' {
                if ($id -notin $ExpectedEnforcedPolicies) {
                    $bad++; $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "$id is enforced ('enabled'): graduate one policy per PR, only after 01-Verify-Baseline.ps1 passes; if it graduated on purpose, name it in -ExpectedEnforcedPolicies"))
                }
            }
            'disabled' { $bad++; $out.Add((ConvertTo-PreflightFinding $c 'WARN' "$id is 'disabled': the plan starts every policy report-only")) }
            default { $bad++; $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "$id has state '$s': not a Conditional Access state (enabledForReportingButNotEnforced, enabled, disabled)")) }
        }
    }
    foreach ($id in @($ExpectedEnforcedPolicies | Where-Object { $_ })) {
        $want = $id.ToUpperInvariant()
        if (-not $states.Contains($want) -or [string]$states[$want] -cne 'enabled') {
            $bad++; $out.Add((ConvertTo-PreflightFinding $c 'WARN' "-ExpectedEnforcedPolicies names $want, but lab.tfvars has it $(if ($states.Contains($want)) { "'$($states[$want])'" } else { 'missing' })"))
        }
    }
    if ($ids.Count -eq 0) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "ca_policy_states in $Path is empty")) }
    elseif ($bad -eq 0) {
        $enforced = @($ids | Where-Object { [string]$states[$_] -ceq 'enabled' })
        $detail = "$($ids.Count) policies, all report-only (enabledForReportingButNotEnforced)"
        if ($enforced.Count) { $detail = "$($ids.Count) policies; enforced by design: $($enforced -join ', '); the rest report-only" }
        $out.Add((ConvertTo-PreflightFinding $c 'PASS' $detail))
    }
    return $out.ToArray()
}

function Get-PowerShellFinding {
    param([AllowNull()][version]$Version)
    $c = 'PowerShell'
    if ($null -eq $Version) { return ConvertTo-PreflightFinding $c 'WARN' 'version not read' }
    if ($Version.Major -lt 7) { return ConvertTo-PreflightFinding $c 'FAIL' "$Version is Windows PowerShell: the lab scripts need PowerShell 7 (#Requires -Version 7.0) - run them in pwsh" }
    if ($Version.Major -gt 7) { return ConvertTo-PreflightFinding $c 'WARN' "pwsh $Version`: the lab is tested on 7.x" }
    return ConvertTo-PreflightFinding $c 'PASS' "pwsh $Version"
}

function Get-ModuleSetFinding {
    # Microsoft Graph sub-modules: all present, all at the CI pin.
    param([Parameter(Mandatory)][string]$Check, [Parameter(Mandatory)][System.Collections.IDictionary]$Installed, [string]$Pin = '')
    $out = [System.Collections.Generic.List[object]]::new()
    $names = @($Installed.Keys)
    $missing = @($names | Where-Object { @($Installed[$_] | Where-Object { $_ }).Count -eq 0 })
    $offPin = @()
    if ($Pin) {
        $want = ConvertTo-PreflightVersion $Pin
        $offPin = @($names | Where-Object { $_ -notin $missing } | Where-Object {
                $have = @($Installed[$_] | Where-Object { $_ } | ForEach-Object { ConvertTo-PreflightVersion ([string]$_) })
                $have -notcontains $want
            })
    }
    $pinArg = if ($Pin) { " -RequiredVersion $Pin" } else { '' }
    if ($missing.Count) { $out.Add((ConvertTo-PreflightFinding $Check 'FAIL' "missing: $($missing -join ', ') - Install-Module <name>$pinArg -Scope CurrentUser")) }
    if ($offPin.Count) {
        $list = @($offPin | ForEach-Object { "$_ (has $((@($Installed[$_]) | Sort-Object -Descending | ForEach-Object { [string]$_ }) -join ', '))" })
        $out.Add((ConvertTo-PreflightFinding $Check 'WARN' "not at the CI pin $Pin`: $($list -join '; '). Test mocks copy cmdlet signatures from the pinned version, and every Graph sub-module must match Microsoft.Graph.Authentication"))
    }
    else {
        # The pin is everywhere, but pwsh auto-loads ONE version per module
        # (normally the newest): a stray newer sub-module mixes versions.
        $newest = [ordered]@{}
        foreach ($n in @($names | Where-Object { $_ -notin $missing })) {
            $newest[$n] = @($Installed[$n] | Where-Object { $_ } | ForEach-Object { ConvertTo-PreflightVersion ([string]$_) } | Where-Object { $_ } | Sort-Object -Descending)[0]
        }
        if (@($newest.Values | ForEach-Object { [string]$_ } | Sort-Object -Unique).Count -gt 1) {
            $list = @($newest.Keys | ForEach-Object { "$_ $($newest[$_])" }) -join ', '
            $out.Add((ConvertTo-PreflightFinding $Check 'WARN' "the newest installed versions differ ($list): pwsh auto-loads the newest, and Graph sub-modules of different versions fail to load together. Uninstall-Module the extra versions, or Import-Module each one -RequiredVersion $Pin first"))
        }
    }
    if ($out.Count -eq 0) {
        $at = if ($Pin) { " at $Pin" } else { '' }
        $out.Add((ConvertTo-PreflightFinding $Check 'PASS' "$($names.Count)/$($names.Count) installed$at"))
    }
    return $out.ToArray()
}

function Get-TestModuleFinding {
    # Pester / PSScriptAnalyzer: a WARN at most - CI runs both on every PR.
    param([Parameter(Mandatory)][string]$Name, [AllowEmptyCollection()][object[]]$Versions = @(), [string]$Minimum = '0.0.0', [string]$Pin = '')
    $have = @($Versions | Where-Object { $_ } | ForEach-Object { ConvertTo-PreflightVersion ([string]$_) } | Where-Object { $_ } | Sort-Object -Descending)
    $pinArg = if ($Pin) { " -RequiredVersion $Pin" } else { '' }
    if ($have.Count -eq 0) { return ConvertTo-PreflightFinding $Name 'WARN' "not installed: Install-Module $Name$pinArg -Scope CurrentUser (the local test run before a PR needs it; CI runs it anyway)" }
    $min = ConvertTo-PreflightVersion $Minimum
    if ($have[0] -lt $min) { return ConvertTo-PreflightFinding $Name 'WARN' "$($have[0]) is older than $Minimum`: Install-Module $Name$pinArg -Scope CurrentUser" }
