function Get-TerraformFinding {
    # terraform: present, satisfies every envs/* required_version, equals the
    # CI pin (the committed lock files and the mocked tests were built with it).
    param(
        [AllowNull()][AllowEmptyString()][string]$Path,
        [AllowNull()][AllowEmptyString()][string]$VersionText,
        [System.Collections.IDictionary]$Constraints = @{},
        [string]$Pin = ''
    )
    $c = 'terraform'
    if (-not $Path) { return @(ConvertTo-PreflightFinding $c 'FAIL' "not on PATH - HashiCorp Terraform $Pin generated the committed .terraform.lock.hcl files (export PATH=`"`$HOME/.local/bin:`$PATH`")") }
    $raw = ''
    if ($VersionText) {
        try { $raw = [string](Get-PreflightValue ($VersionText | ConvertFrom-Json) 'terraform_version') } catch { $raw = $VersionText }
    }
    $v = ConvertTo-PreflightVersion $raw
    if (-not $v) { return @(ConvertTo-PreflightFinding $c 'FAIL' "on PATH, but 'terraform version' could not be read") }
    $out = [System.Collections.Generic.List[object]]::new()
    $ok = @()
    foreach ($root in @($Constraints.Keys)) {
        $want = [string]$Constraints[$root]
        if (-not $want) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "no required_version found in lab/terraform/$root/versions.tf")); continue }
        try {
            if (Test-VersionConstraint -Version $v -Constraint $want) { $ok += "$root $want" }
            else { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "$v does not satisfy $root required_version `"$want`"")) }
        }
        catch { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "$root required_version `"$want`": $($_.Exception.Message)")) }
    }
    $pinV = ConvertTo-PreflightVersion $Pin
    if ($pinV -and $v -ne $pinV) {
        $out.Add((ConvertTo-PreflightFinding $c 'WARN' "$v differs from the CI pin $Pin`: the committed .terraform.lock.hcl files and mocks were built with $Pin, and init may rewrite a lock file (git checkout it if so)"))
    }
    if (@($out | Where-Object { $_.Status -ne 'PASS' }).Count -eq 0) {
        $sat = if ($ok.Count) { "; satisfies $($ok -join ', ')" } else { '' }
        $out.Add((ConvertTo-PreflightFinding $c 'PASS' "$v (CI pin $Pin)$sat"))
    }
    return $out.ToArray()
}

