# PURE FUNCTIONS (no I/O) - tests/00-Preflight.Tests.ps1 loads them from this
# file's syntax tree.
# =============================================================================
function ConvertTo-PreflightFinding {
    # One result row. Every detail is redacted here, so no check can leak a
    # GUID (tenant / subscription / object id), a JWT, a bearer or GitHub
    # token, URL credentials, a UPN / email address (az and Graph error texts
    # name the signed-in user) or a home-folder path.
    param([Parameter(Mandatory)][string]$Check, [Parameter(Mandatory)][ValidateSet('PASS', 'WARN', 'FAIL')][string]$Status, [string]$Detail = '')
    $safe = $Detail -replace '(?i)\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b', '<id>'
    $safe = $safe -replace 'eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]*', '<token>'
    $safe = $safe -replace '(?i)\b(Bearer\s+)[A-Za-z0-9._~+/=-]{16,}', '$1<token>'
    $safe = $safe -replace '\bgh[pousr]_[A-Za-z0-9]{20,}', '<token>'
    $safe = $safe -replace '(?<=://)[^/@\s]+@', ''
    $safe = $safe -replace '(?i)\b[A-Z0-9._%+-]+@[A-Z0-9-]+(\.[A-Z0-9-]+)*\.[A-Z]{2,}\b', '<upn>'
    $safe = $safe -replace '(?i)(/Users/|/home/|\b[A-Z]:\\Users\\)[^/\\\s''"]+', '~'
    return [pscustomobject]@{ Check = $Check; Status = $Status; Detail = $safe }
}

function Get-PreflightValue {
    # Key or property, $null when absent: StrictMode-safe for hashtables
    # (Invoke-MgGraphRequest -OutputType HashTable) and PSCustomObjects
    # (ConvertFrom-Json) alike.
    param([AllowNull()]$Object, [Parameter(Mandatory)][string]$Name)
    if ($null -eq $Object) { return $null }
    if ($Object -is [System.Collections.IDictionary]) {
        if ($Object.Contains($Name)) { return $Object[$Name] }
        return $null
    }
    $p = $Object.PSObject.Properties[$Name]
    if ($p) { return $p.Value }
    return $null
}

function ConvertTo-PreflightVersion {
    # First "major.minor[.patch]" in a tool's version output, as a 3-part
    # [version] (so comparisons never trip over a missing component).
    param([AllowNull()][AllowEmptyString()][string]$Text)
    if (-not $Text) { return $null }
    $m = [regex]::Match($Text, '(\d+)\.(\d+)(?:\.(\d+))?')
    if (-not $m.Success) { return $null }
    $patch = 0
    if ($m.Groups[3].Success) { $patch = [int]$m.Groups[3].Value }
    return [version]::new([int]$m.Groups[1].Value, [int]$m.Groups[2].Value, $patch)
}

function Test-VersionConstraint {
    # Terraform version constraint syntax: ">= 1.9.0", "~> 1.6", ">= 1.6, < 2.0".
    param([Parameter(Mandatory)][version]$Version, [Parameter(Mandatory)][string]$Constraint)
    foreach ($part in ($Constraint -split ',')) {
        $p = $part.Trim()
        if (-not $p) { continue }
        $m = [regex]::Match($p, '^(>=|<=|!=|~>|>|<|=)?\s*v?(\d+(?:\.\d+){0,2})$')
        if (-not $m.Success) { throw "unsupported version constraint '$p'" }
        $op = '='
        if ($m.Groups[1].Success -and $m.Groups[1].Value) { $op = $m.Groups[1].Value }
        $segs = @($m.Groups[2].Value -split '\.' | ForEach-Object { [int]$_ })
        $n = @($segs + @(0, 0, 0))[0..2]
        $want = [version]::new($n[0], $n[1], $n[2])
        $ok = switch ($op) {
            '=' { $Version -eq $want }
            '!=' { $Version -ne $want }
            '>' { $Version -gt $want }
            '>=' { $Version -ge $want }
            '<' { $Version -lt $want }
            '<=' { $Version -le $want }
            '~>' {
                # Only the rightmost given component may grow: ~> 1.2.3 = >= 1.2.3, < 1.3.0; ~> 1.2 = >= 1.2.0, < 2.0.0.
                $upper = if ($segs.Count -ge 3) { [version]::new($want.Major, $want.Minor + 1, 0) } else { [version]::new($want.Major + 1, 0, 0) }
                ($Version -ge $want) -and ($Version -lt $upper)
            }
        }
        if (-not $ok) { return $false }
    }
    return $true
}

function Get-TerraformRequiredVersion {
    # The root module's required_version string from a versions.tf, or $null.
    param([AllowNull()][AllowEmptyString()][string]$Text)
    if (-not $Text) { return $null }
    $m = [regex]::Match($Text, '(?m)^\s*required_version\s*=\s*"([^"]+)"')
    if ($m.Success) { return $m.Groups[1].Value }
    return $null
}

function Get-CiPin {
    # First capture of $Pattern in a workflow file, else $Default.
    param([AllowNull()][AllowEmptyString()][string]$Text, [Parameter(Mandatory)][string]$Pattern, [string]$Default = '')
    if ($Text) {
        $m = [regex]::Match($Text, $Pattern)
        if ($m.Success) { return $m.Groups[1].Value }
