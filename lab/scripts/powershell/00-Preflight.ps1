function Get-PreflightGraphCollection {
    param([Parameter(Mandatory)][string]$Uri)
    $items = [System.Collections.Generic.List[object]]::new(); $next = $Uri
    while ($next) {
        $page = Invoke-PreflightGraph -Uri $next
        foreach ($v in @(Get-PreflightValue $page 'value')) { if ($null -ne $v) { $items.Add($v) } }
        $next = [string](Get-PreflightValue $page '@odata.nextLink')
    }
    return $items.ToArray()
}

function Invoke-Preflight {
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidUsingWriteHost', '', Justification = 'Interactive operator console (colour, -NoNewline): status lines for the person running the script, not pipeline data.')]
    param(
        [switch]$Offline,
        [string]$OnMicrosoftDomain = '',
        [AllowEmptyCollection()][string[]]$ExpectedOnFlags = @(),
        [AllowEmptyCollection()][string[]]$ExpectedEnforcedPolicies = @(),
        [switch]$PreTrial,
        [string[]]$E5SkuPartNumbers = @('SPE_E5', 'Microsoft_365_E5_(no_Teams)'),
        [string[]]$GovernanceSkuPartNumbers = @('Microsoft_Entra_ID_Governance'),
        [int]$BudgetCapUsd = 150,
        [Parameter(Mandatory)][string]$RepoRoot
    )
    $d = Get-PreflightDefault
    $results = [System.Collections.Generic.List[object]]::new()
    $total = if ($Offline) { 4 } else { 6 }
    $emit = {
        param($Findings)
        foreach ($f in @($Findings)) {
            if ($null -eq $f) { continue }
            $results.Add($f)
            $color = @{ PASS = 'Green'; WARN = 'Yellow'; FAIL = 'Red' }[$f.Status]
            Write-Host ('  [{0}] {1} - {2}' -f $f.Status, $f.Check, $f.Detail) -ForegroundColor $color
        }
    }
    $section = { param([int]$N, [string]$Title) Write-Host "`n[$N/$total] $Title" -ForegroundColor Cyan }
    $readText = {
        param([string]$Rel)
        $p = Join-Path $RepoRoot $Rel
        if (Test-Path -LiteralPath $p -PathType Leaf) { return [string](Get-Content -LiteralPath $p -Raw) }
        return $null
    }
    $mode = if ($Offline) { 'offline: local tools and repo only, no az, no Graph' } else { 'online: local, then the az session and the Graph connection' }
    Write-Host "Tenant-day preflight ($mode). Read-only: no sign-in, no changes." -ForegroundColor Cyan

    # ---- [1] PowerShell and modules -------------------------------------------
    & $section 1 'PowerShell and modules'
    & $emit (Get-PowerShellFinding -Version (Get-PreflightPsVersion))
    $labTests = & $readText '.github/workflows/lab-tests.yml'
    $graphPin = Get-CiPin -Text $labTests -Pattern 'Install-Module\s+\$m\s+-RequiredVersion\s+([0-9.]+)' -Default $d.GraphPin
    $pesterPin = Get-CiPin -Text $labTests -Pattern 'Install-Module\s+Pester\s+-RequiredVersion\s+([0-9.]+)' -Default $d.PesterPin
    $pssaPin = Get-CiPin -Text $labTests -Pattern 'Install-Module\s+PSScriptAnalyzer\s+-RequiredVersion\s+([0-9.]+)' -Default $d.AnalyzerPin
    $graphModules = @($d.GraphModules)
    if ($labTests) {
        $fromCi = @([regex]::Matches($labTests, "'(Microsoft\.Graph\.[A-Za-z.]+)'") | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique)
        if ($fromCi.Count) { $graphModules = $fromCi }
    }
    $installed = [ordered]@{}
    foreach ($m in $graphModules) { $installed[$m] = @(Get-PreflightModuleVersion -Name $m) }
    & $emit (Get-ModuleSetFinding -Check 'Microsoft Graph modules' -Installed $installed -Pin $graphPin)
    & $emit (Get-TestModuleFinding -Name 'Pester' -Versions @(Get-PreflightModuleVersion -Name 'Pester') -Minimum $d.PesterMinimum -Pin $pesterPin)
    & $emit (Get-TestModuleFinding -Name 'PSScriptAnalyzer' -Versions @(Get-PreflightModuleVersion -Name 'PSScriptAnalyzer') -Pin $pssaPin)

    # ---- [2] Command-line tools -----------------------------------------------
    & $section 2 'Command-line tools'
    $tfPin = Get-CiPin -Text (& $readText '.github/workflows/terraform-apply.yml') -Pattern 'terraform_version:\s*"([0-9.]+)"' -Default $d.TerraformPin
    # Every root under lab/terraform/envs (dev and bootstrap today).
    $envRoots = @('envs/bootstrap', 'envs/dev')
    $envDir = Join-Path $RepoRoot 'lab/terraform/envs'
    if (Test-Path -LiteralPath $envDir -PathType Container) {
        $found = @(Get-ChildItem -LiteralPath $envDir -Directory | Where-Object { $_.Name -notlike '.*' } | Sort-Object Name | ForEach-Object { "envs/$($_.Name)" })
        if ($found.Count) { $envRoots = $found }
    }
    $constraints = [ordered]@{}
    foreach ($root in $envRoots) { $constraints[$root] = Get-TerraformRequiredVersion (& $readText "lab/terraform/$root/versions.tf") }
    $tfPath = Get-PreflightCommandPath -Name 'terraform'
    $tfOut = $null
    if ($tfPath) { $tfOut = (Invoke-PreflightNative -Name 'terraform' -Arguments @('version', '-json')).Output }
    & $emit (Get-TerraformFinding -Path $tfPath -VersionText $tfOut -Constraints $constraints -Pin $tfPin)
    $azPath = Get-PreflightCommandPath -Name 'az'
    $azPurpose = 'az login, the Terraform backend, budgets'
    $azFix = 'Install the Azure CLI before the first az login'
    $loginArgs = $null; $loginErr = ''
    if ($Offline -or -not $azPath) {
        & $emit (Get-ToolFinding -Name 'az (Azure CLI)' -Path $azPath -PresenceOnly -Purpose $azPurpose -Fix $azFix -PresenceNote '; version not read offline - any az command may send telemetry')
    }
    else {
        # Read az's login log BEFORE the first az command: every az command
        # writes a log of its own and az prunes the oldest ones.
        try { $loginArgs = Get-PreflightAzLoginArgument } catch { $loginErr = $_.Exception.Message }
        $azv = Invoke-PreflightNative -Name 'az' -Arguments @('version', '-o', 'json')
        & $emit (Get-ToolFinding -Name 'az (Azure CLI)' -Path $azPath -VersionText $azv.Output -VersionPattern '"azure-cli"\s*:\s*"([^"]+)"' -Purpose $azPurpose -Fix $azFix)
    }
    $tools = @(
        @{ Name = 'gitleaks'; Args = @('version'); Missing = 'FAIL'; Purpose = 'the pre-push secret gate'; Pattern = '' }
        # --no-update: trufflehog otherwise may check for a new release online.
        @{ Name = 'trufflehog'; Args = @('--no-update', '--version'); Missing = 'FAIL'; Purpose = 'the pre-push secret gate'; Pattern = '' }
        @{ Name = 'shellcheck'; Args = @('--version'); Missing = 'WARN'; Purpose = 'shell lint before a PR'; Pattern = 'version:\s*(\S+)' }
        @{ Name = 'actionlint'; Args = @('-version'); Missing = 'WARN'; Purpose = 'workflow lint before a PR'; Pattern = '' }
        # Version only: `gh auth status` would call GitHub. Run it yourself.
        @{ Name = 'gh'; Args = @('--version'); Missing = 'WARN'; Purpose = 'GitHub CLI: gh auth status, gh workflow run / gh run watch'; Pattern = 'gh version\s+(\S+)' }
    )
    foreach ($t in $tools) {
        $p = Get-PreflightCommandPath -Name $t.Name
        $vt = $null
        if ($p) { $r = Invoke-PreflightNative -Name $t.Name -Arguments $t.Args; $vt = (@($r.Output, $r.ErrorText) | Where-Object { $_ }) -join "`n" }
        & $emit (Get-ToolFinding -Name $t.Name -Path $p -VersionText $vt -MissingStatus $t.Missing -Purpose $t.Purpose -VersionPattern $t.Pattern -Fix 'Install it on PATH (e.g. ~/.local/bin)')
    }

    # ---- [3] Containers -------------------------------------------------------
    & $section 3 'Containers (PAM / IGA stand-ins)'
    $colPath = Get-PreflightCommandPath -Name 'colima'
    $colVer = $null
    if ($colPath) { $colVer = (Invoke-PreflightNative -Name 'colima' -Arguments @('version')).Output }
    $dkPath = Get-PreflightCommandPath -Name 'docker'
    $dkVer = $null; $daemon = [pscustomobject]@{ ExitCode = 1; Output = '' }
    if ($dkPath) {
        $dkVer = (Invoke-PreflightNative -Name 'docker' -Arguments @('--version')).Output
        $daemon = Invoke-PreflightNative -Name 'docker' -Arguments @('info', '--format', '{{.ServerVersion}}')
    }
    & $emit (Get-ContainerFinding -ColimaPath $colPath -ColimaVersionText $colVer -DockerPath $dkPath -DockerVersionText $dkVer -DaemonExitCode $daemon.ExitCode -DaemonVersionText $daemon.Output -StartHint $d.ColimaStart)

    # ---- [4] Repository ---------------------------------------------------------
    & $section 4 'Repository and lab.tfvars'
    if (-not (Get-PreflightCommandPath -Name 'git')) { & $emit (ConvertTo-PreflightFinding 'git' 'FAIL' 'not on PATH - every flag flip is a PR') }
    else {
        # --no-optional-locks: `git status` would otherwise refresh (write) the
        # index and can collide with an editor or another git running here.
        $git = { param([string[]]$GitArgs) Invoke-PreflightNative -Name 'git' -Arguments (@('--no-optional-locks', '-C', $RepoRoot) + $GitArgs) }
        $top = & $git @('rev-parse', '--show-toplevel')
        $isRepo = $top.ExitCode -eq 0
        $status = $null; $remotes = @()
        if ($isRepo) {
            $st = & $git @('status', '--porcelain=v1', '--branch')
            if ($st.ExitCode -eq 0) { $status = ConvertFrom-GitStatus -Text $st.Output }
            $remotes = @(ConvertFrom-GitRemote -Text (& $git @('remote', '-v')).Output)
        }
        & $emit (Get-GitFinding -IsRepo $isRepo -Status $status -Remotes $remotes -IsBuildSource (Test-Path -LiteralPath (Join-Path $RepoRoot 'build/make-public-repo.sh') -PathType Leaf))
    }
    $tfvarsText = & $readText 'lab/terraform/envs/dev/lab.tfvars'
    $parsed = $null
    if ($null -ne $tfvarsText) { $parsed = Read-LabTfvarsFile -Text $tfvarsText }
    & $emit (Get-TfvarsFinding -Parsed $parsed -ExpectedOnFlags $ExpectedOnFlags -ExpectedEnforcedPolicies $ExpectedEnforcedPolicies)
    $premiumOn = $false
    if ($parsed -and $parsed.Flags.Contains('enable_premium')) { $premiumOn = [bool]$parsed.Flags['enable_premium'] }

    if (-not $Offline) {
        # ---- [5] Azure CLI session --------------------------------------------
        & $section 5 'Azure CLI session (read-only)'
        $azTenantId = ''
        if (-not $azPath) { & $emit (ConvertTo-PreflightFinding 'Azure CLI sign-in' 'FAIL' 'not checked: az is not installed (see [2/6])') }
        else {
            $acct = Invoke-PreflightNative -Name 'az' -Arguments @('account', 'show', '-o', 'json')
            $account = $null
            if ($acct.ExitCode -eq 0) { $account = ConvertFrom-AzAccount -Json $acct.Output }
            & $emit (Get-AzAccountFinding -Account $account -ExpectedDomain $OnMicrosoftDomain)
            $signedIn = $null -ne $account
            $hasSub = $signedIn -and $account.HasSubscription
            if ($signedIn) { $azTenantId = $account.TenantId }
            & $emit (Get-AzLoginMethodFinding -LastLoginArgs $loginArgs -SignedIn $signedIn -ReadError $loginErr)
            $budgets = $null; $bErr = ''
            if ($hasSub) {
                $b = Invoke-PreflightNative -Name 'az' -Arguments @('consumption', 'budget', 'list', '-o', 'json')
                if ($b.ExitCode -eq 0) {
                    try { $budgets = @(($b.Output | ConvertFrom-Json) | ForEach-Object { $_ }) } catch { $bErr = 'unreadable JSON' }
                }
                else { $bErr = Get-AzErrorLine -Text $b.ErrorText -ExitCode $b.ExitCode }
            }
            & $emit (Get-BudgetFinding -Budgets $budgets -ReadError $bErr -CapUsd $BudgetCapUsd -SignedIn $signedIn -HasSubscription $hasSub)
        }

        # ---- [6] Microsoft Graph ------------------------------------------------
        & $section 6 'Microsoft Graph (read-only)'
        $scopeFiles = @()
        $postApply = Join-Path $RepoRoot 'lab/scripts/powershell/post-apply'
        if (Test-Path -LiteralPath $postApply -PathType Container) { $scopeFiles += @(Get-ChildItem -LiteralPath $postApply -Filter '*.ps1' -File | ForEach-Object { $_.FullName }) }
        $gate = Join-Path $RepoRoot 'lab/scripts/powershell/01-Verify-Baseline.ps1'
        if (Test-Path -LiteralPath $gate -PathType Leaf) { $scopeFiles += $gate }
        $set = Get-PostApplyScopeSet -Path $scopeFiles
        $source = "declared by $($set.FilesRead) post-apply / gate script(s) + this preflight"
        $declared = @($set.Scopes)
        if ($declared.Count -eq 0) { $declared = @($d.FallbackScopes); $source = 'fallback list: the post-apply scripts were not readable' }
        $optional = @($declared | Where-Object { $_ -match $d.OptionalScopePattern })
        $required = @(@($declared | Where-Object { $_ -notmatch $d.OptionalScopePattern }) + @($d.PreflightScopes) | Sort-Object -Unique)

        $ctx = Get-PreflightGraphContext
        & $emit (Get-GraphContextFinding -Context $ctx -AzTenantId $azTenantId -ConnectScopes $required)
        if (@($set.ParseErrors).Count) {
            & $emit (ConvertTo-PreflightFinding 'Delegated Graph scopes' 'WARN' "$(@($set.ParseErrors) -join ', ') did not parse (mid-edit?): its `$requiredScopes may be missing from the scope list")
        }
        if ($null -eq $ctx) {
            foreach ($c in @('Graph tenant', 'Licensed SKUs', 'Break-glass accounts (bg-admin-*)')) { & $emit (ConvertTo-PreflightFinding $c 'FAIL' 'not checked: no Microsoft Graph connection') }
        }
        else {
            & $emit (Get-ScopeFinding -Granted @(Get-PreflightValue $ctx 'Scopes') -Required $required -Optional $optional -Source $source)
            try {
                $org = @(Get-PreflightGraphCollection -Uri "$($d.Graph)/organization?`$select=displayName,verifiedDomains")
                & $emit (Get-TenantDomainFinding -Organization $(if ($org.Count) { $org[0] } else { $null }) -ExpectedDomain $OnMicrosoftDomain)
            }
            catch { & $emit (Get-TenantDomainFinding -ReadError $_.Exception.Message) }
            try {
                $skus = @(Get-PreflightGraphCollection -Uri "$($d.Graph)/subscribedSkus")
                & $emit (Get-SkuFinding -Skus $skus -E5PartNumbers $E5SkuPartNumbers -GovernancePartNumbers $GovernanceSkuPartNumbers -PreTrial:$PreTrial)
            }
            catch { & $emit (Get-SkuFinding -E5PartNumbers $E5SkuPartNumbers -GovernancePartNumbers $GovernanceSkuPartNumbers -ReadError $_.Exception.Message) }
            try {
                $f = [uri]::EscapeDataString("startswith(mailNickname,'bg-admin-')")
                $users = @(Get-PreflightGraphCollection -Uri "$($d.Graph)/users?`$filter=$f&`$select=mailNickname,userPrincipalName,accountEnabled,assignedLicenses")
                & $emit (Get-BreakGlassFinding -Users $users -PremiumOn $premiumOn -PreTrial:$PreTrial)
            }
            catch { & $emit (Get-BreakGlassFinding -ReadError $_.Exception.Message) }
        }
    }

    # ---- Summary ---------------------------------------------------------------
    $code = Get-PreflightExitCode -Results $results.ToArray()
    $fails = @($results | Where-Object { $_.Status -eq 'FAIL' }).Count
    $warns = @($results | Where-Object { $_.Status -eq 'WARN' }).Count
    $verdict = @('READY', 'READY WITH WARNINGS - read each WARN', 'BLOCKED - fix every FAIL first')[$code]
    $color = @('Green', 'Yellow', 'Red')[$code]
    Write-Host "`nPreflight: $fails FAIL, $warns WARN, $($results.Count - $fails - $warns) PASS - $verdict (exit $code)" -ForegroundColor $color
    Write-Host "Budget: `$$BudgetCapUsd cap. Every morning: recurring billing Off on every trial (M365 admin center > Billing > Your products)." -ForegroundColor DarkGray
    return [pscustomobject]@{ ExitCode = $code; Results = $results.ToArray() }
}

# =============================================================================
# MAIN
# =============================================================================
if (-not $RepoRoot) { $RepoRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot (Join-Path '..' (Join-Path '..' '..')))) }
# An unexpected error is BLOCKED (2), never the "warnings only" 1 that an
# unhandled throw gives `pwsh -File` (or a stale $LASTEXITCODE in-session).
try {
    $run = Invoke-Preflight -Offline:$Offline -OnMicrosoftDomain $OnMicrosoftDomain -ExpectedOnFlags $ExpectedOnFlags `
        -ExpectedEnforcedPolicies $ExpectedEnforcedPolicies -PreTrial:$PreTrial -E5SkuPartNumbers $E5SkuPartNumbers `
        -GovernanceSkuPartNumbers $GovernanceSkuPartNumbers -BudgetCapUsd $BudgetCapUsd -RepoRoot $RepoRoot
    $exitCode = [int]$run.ExitCode
}
catch {
    $crash = ConvertTo-PreflightFinding 'Preflight' 'FAIL' "stopped on an unexpected error at line $($_.InvocationInfo.ScriptLineNumber): $($_.Exception.Message)"
    Write-Console ('  [{0}] {1} - {2}' -f $crash.Status, $crash.Check, $crash.Detail) -ForegroundColor Red
    Write-Console "`nPreflight: did not finish - BLOCKED until it runs to the end (exit 2)" -ForegroundColor Red
    $exitCode = 2
}
exit $exitCode
