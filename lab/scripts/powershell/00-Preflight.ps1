    $out = [System.Collections.Generic.List[object]]::new()
    $e5Part = ''
    foreach ($want in @(
            @{ Check = 'Microsoft 365 E5'; Parts = $E5PartNumbers; Param = '-E5SkuPartNumbers' },
            @{ Check = 'Microsoft Entra ID Governance'; Parts = $GovernancePartNumbers; Param = '-GovernanceSkuPartNumbers' })) {
        $hits = @($all | Where-Object { [string](Get-PreflightValue $_ 'skuPartNumber') -in $want.Parts } |
                Sort-Object { $s = [string](Get-PreflightValue $_ 'capabilityStatus'); if ($rank.ContainsKey($s)) { $rank[$s] } else { 9 } })
        if ($hits.Count -eq 0) {
            $next = if ($PreTrial) { 'Expected before Day 0 (-PreTrial).' } else { "Start the trial (Day 0, recurring billing Off); if it shows another part number, pass it with $($want.Param) (verify: the trial's skuPartNumber)." }
            $out.Add((ConvertTo-PreflightFinding $want.Check $missingStatus "not in subscribedSkus (looked for $($want.Parts -join ', '); the tenant has: $have). $next"))
            continue
        }
        if ($want.Check -eq 'Microsoft 365 E5') { $e5Part = [string](Get-PreflightValue $hits[0] 'skuPartNumber') }
        $out.Add((Get-SkuStatusFinding -Check $want.Check -Sku $hits[0] -PreTrial:$PreTrial))
    }
    $p2 = @($active | Where-Object { (& $plansOf $_) -contains 'AAD_PREMIUM_P2' } | ForEach-Object { [string](Get-PreflightValue $_ 'skuPartNumber') })
    if ($p2.Count) { $out.Add((ConvertTo-PreflightFinding 'Entra ID P2 service plan' 'PASS' "AAD_PREMIUM_P2 via $($p2 -join ', ')")) }
    else { $out.Add((ConvertTo-PreflightFinding 'Entra ID P2 service plan' $missingStatus 'no active SKU carries AAD_PREMIUM_P2: PIM, ID Protection (CA006 / CA007) and the risk captures need it')) }
    if ($e5Part -like '*no_Teams*') {
        $teams = @($active | Where-Object { (& $plansOf $_) -contains 'TEAMS1' })
        if ($teams.Count -eq 0) { $out.Add((ConvertTo-PreflightFinding 'Microsoft Teams' 'WARN' 'E5 is the (no Teams) SKU and no active SKU carries TEAMS1: start the Teams trial by Day 2 - the E18 notify card and the E41 containment approval need it')) }
    }
    return $out.ToArray()
}

function Get-BreakGlassFinding {
    # Existence and hygiene only. CA exclusion + Global Administrator are
    # 01-Verify-Baseline.ps1's checks 2-4.
    param(
        [AllowNull()][AllowEmptyCollection()][object[]]$Users = @(),
        [bool]$PremiumOn = $false,
        [switch]$PreTrial,
        [string]$ReadError = ''
    )
    $c = 'Break-glass accounts (bg-admin-*)'
    if ($ReadError) { return @(ConvertTo-PreflightFinding $c 'FAIL' "could not read users: $ReadError") }
    $u = @($Users | Where-Object { $null -ne $_ })
    if ($u.Count -eq 0) {
        if ($PremiumOn) { return @(ConvertTo-PreflightFinding $c 'FAIL' 'none found, but enable_premium is on in lab.tfvars: Conditional Access can exist without its lockout exclusion - apply envs/dev, then run 01-Verify-Baseline.ps1 before anything else') }
        return @(ConvertTo-PreflightFinding $c 'WARN' 'none yet: Terraform creates bg-admin-01/02 when enable_premium flips (Day 1, PR #1; no CA policy exists before that). Register their keys and run 01-Verify-Baseline.ps1 right after that apply')
    }
    $out = [System.Collections.Generic.List[object]]::new()
    $nicks = @($u | ForEach-Object { [string](Get-PreflightValue $_ 'mailNickname') } | Sort-Object)
    if ($u.Count -lt 2) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "found $($u.Count) ($($nicks -join ', ')): keep at least two")) }
    $unlicensed = @()
    foreach ($x in $u) {
        $nick = [string](Get-PreflightValue $x 'mailNickname')
        $problems = @()
        if ((Get-PreflightValue $x 'accountEnabled') -ne $true) { $problems += 'disabled' }
        if (-not ([string](Get-PreflightValue $x 'userPrincipalName') -like '*.onmicrosoft.com')) { $problems += 'not on the *.onmicrosoft.com domain' }
        if ($problems) { $out.Add((ConvertTo-PreflightFinding $c 'FAIL' "$nick`: $($problems -join '; ')")) }
        elseif (@(Get-PreflightValue $x 'assignedLicenses' | Where-Object { $null -ne $_ }).Count -eq 0) { $unlicensed += $nick }
    }
    if ($unlicensed.Count -and -not $PreTrial) { $out.Add((ConvertTo-PreflightFinding $c 'WARN' "no licence assigned: $($unlicensed -join ', ') (Day 0: E5 + Governance on both break-glass accounts)")) }
    if ($out.Count -eq 0) {
        $lic = if ($unlicensed.Count) { '' } else { ', licensed' }
        $out.Add((ConvertTo-PreflightFinding $c 'PASS' "$($u.Count) found ($($nicks -join ', ')): enabled, on *.onmicrosoft.com$lic. CA exclusion and Global Administrator: 01-Verify-Baseline.ps1"))
    }
    return $out.ToArray()
}

function Get-PreflightExitCode {
    # 0 ready, 1 ready with warnings, 2 blocked.
    param([AllowEmptyCollection()][object[]]$Results = @())
    if (@($Results | Where-Object { $_ -and $_.Status -eq 'FAIL' }).Count) { return 2 }
    if (@($Results | Where-Object { $_ -and $_.Status -eq 'WARN' }).Count) { return 1 }
    return 0
}

