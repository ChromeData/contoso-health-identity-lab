function Get-PreflightCommandPath {
    param([Parameter(Mandatory)][string]$Name)
    $cmd = Get-Command -Name $Name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($cmd) { return [string]$cmd.Source }
    return $null
}

function Invoke-PreflightNative {
    # Runs a local executable; stdout and stderr come back separately.
    param([Parameter(Mandatory)][string]$Name, [AllowEmptyCollection()][string[]]$Arguments = @())
    $path = Get-PreflightCommandPath -Name $Name
    if (-not $path) { return [pscustomobject]@{ ExitCode = 127; Output = ''; ErrorText = "$Name is not on PATH" } }
    $ErrorActionPreference = 'Continue'
    $prev = $env:CHECKPOINT_DISABLE
    $env:CHECKPOINT_DISABLE = '1'    # no Terraform update check over the network
    try {
        $all = @(& $path @Arguments 2>&1)
        $code = $LASTEXITCODE
    }
    catch { return [pscustomobject]@{ ExitCode = 1; Output = ''; ErrorText = $_.Exception.Message } }
    finally { $env:CHECKPOINT_DISABLE = $prev }
    $stdout = @($all | Where-Object { $_ -isnot [System.Management.Automation.ErrorRecord] } | ForEach-Object { [string]$_ }) -join "`n"
    $stderr = @($all | Where-Object { $_ -is [System.Management.Automation.ErrorRecord] } | ForEach-Object { $_.ToString() }) -join "`n"
    if ($null -eq $code) { $code = 0 }
    return [pscustomobject]@{ ExitCode = [int]$code; Output = $stdout; ErrorText = $stderr }
}

function Get-PreflightModuleVersion {
    param([Parameter(Mandatory)][string]$Name)
    return @(Get-Module -ListAvailable -Name $Name -ErrorAction SilentlyContinue | ForEach-Object { $_.Version })
}

function Get-PreflightPsVersion {
    return ConvertTo-PreflightVersion ([string]$PSVersionTable.PSVersion)
}

function Get-PreflightGraphContext {
    if (-not (Get-Command -Name Get-MgContext -ErrorAction SilentlyContinue)) { return $null }
    try { return Get-MgContext } catch { return $null }
}

function Invoke-PreflightGraph {
    # GET only.
    param([Parameter(Mandatory)][string]$Uri)
    return Invoke-MgGraphRequest -Method GET -Uri $Uri -OutputType HashTable
}

function Get-PreflightAzLoginArgument {
    # Arguments of the most recent `az login` in az's own command log
    # (<config dir>/commands/*.login.*.log, "command args: login ..."; values
    # are logged as {} but flags are not). $null = no login log left; an
    # unreadable folder or log throws (reported as a WARN, never as "none").
    $dir = if ($env:AZURE_CONFIG_DIR) { $env:AZURE_CONFIG_DIR } else { Join-Path $HOME '.azure' }
    $cmdDir = Join-Path $dir 'commands'
    if (-not (Test-Path -LiteralPath $cmdDir -PathType Container)) { return $null }
    $f = Get-ChildItem -LiteralPath $cmdDir -Filter '*.login.*.log' -File -ErrorAction Stop | Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1
    if (-not $f) { return $null }
    $hit = Select-String -LiteralPath $f.FullName -Pattern 'command args:\s*(.*)$' -ErrorAction Stop | Select-Object -First 1
    if (-not $hit) { return '' }
    return $hit.Matches[0].Groups[1].Value
}

